// ПРИЗРАЧНЫЙ ТЕКСТ (слово автора 22.11: «дрожащий текст на экране с эффектом призрачности»).
// Слова без носителя — шёпоты мест, строка покоя и строка на ходу под ногами, слова сети (свои и чужие) —
// дрожат и двоятся: основной оттиск подрагивает на точку, за ним бледный двойник,
// который не поспевает и медленно плывёт. Яркость дышит, без провалов.
// Бумага (осмотр, терминал, таблички, печати, опись, записки) не дрожит: бумага стоит твёрдо.
// «Меньше движения» (системная настройка; графа быта в core/prefs.js снята): ни дрожи, ни дрейфа,
// ни дыхания — двойник стоит рядом, бледно.
// ═══════════════════════════════════════
import { t } from '../core/time.js';
import { reducedMotion } from '../core/prefs.js';

// двойник — доля яркости основного оттиска
export const GHOST_A = 0.5;

const hash = n => {
  n = (n ^ 61) ^ (n >>> 16); n = (n + (n << 3)) | 0; n ^= n >>> 4;
  n = Math.imul(n, 0x27d4eb2d); n ^= n >>> 15;
  return (n >>> 0) / 4294967296;
};
// своё зерно у каждой строки: дрожат не в такт
export function ghostSeed(text) {
  let h = 7;
  for (const ch of String(text || '')) h = (Math.imul(h, 31) + ch.charCodeAt(0)) | 0;
  return h & 0xffff;
}

// дрожь: раз в три шага — новое положение; чаще на месте, иногда на точку вбок или по высоте
export function tremble(seed = 0) {
  if (reducedMotion()) return [0, 0];
  const k = (t / 3) | 0, r = hash(k * 977 + seed * 131);
  if (r < 0.6) return [0, 0];
  const s = hash(k * 389 + seed * 71 + 7) < 0.5 ? -1 : 1;
  return r < 0.82 ? [s, 0] : [0, s];
}

// двойник: отстаёт на одну-три точки и медленно плывёт
export function ghostShift(seed = 0) {
  if (reducedMotion()) return [2, -1];
  const ph = t * 0.021 + (seed % 97) * 0.37;
  return [Math.round(2 + Math.sin(ph) * 1.4), Math.round(-1 + Math.sin(ph * 0.63 + 1) * 1.1)];
}

// дыхание яркости: медленно, без провалов (полный вдох — секунды за две с половиной)
export function flicker(seed = 0) {
  if (reducedMotion()) return 1;
  return 0.92 + 0.08 * Math.sin(t * 0.042 + (seed % 89) * 0.53);
}

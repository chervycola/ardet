// All signs flattened with segment back-pointer (for tests + flat queries)
export function allSigns() {
  const out = [];
  const push = (seg) => seg.signs.forEach(s => out.push({ ...s, _segment: seg.id }));
  push(TOWNLET);
  SEGMENTS.forEach(push);
  return out;
}

// Find which segment contains a given world x
export function segmentAt(x) {
  if (x < TOWNLET.range[1]) return TOWNLET;
  return SEGMENTS.find(s => x >= s.range[0] && x < s.range[1])
    || SEGMENTS[SEGMENTS.length - 1];
}


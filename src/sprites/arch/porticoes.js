function R(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(x, y, w, h); }
const q = Math.round;

// ступенчатая масса снизу вверх: hws — полуширины рядов, rh — высота ряда;
// открытые ступени подсвечены слева (и справа, если both)
function stack(c, cx, base, hws, rh, body, lit, both) {
  for (let k = 0; k < hws.length; k++) {
    const hw = hws[k], hn = k + 1 < hws.length ? hws[k + 1] : 0, y = base - (k + 1) * rh;
    const e = Math.max(1, hw - hn);
    R(c, body, cx - hw, y, hw * 2, rh);
    R(c, lit, cx - hw, y, e, 1);
    if (both) R(c, lit, cx + hw - e, y, e, 1);
  }
}

// ряды по центру снизу вверх: list — [ширина, высота]
function rows(c, col, cx, base, list) {
  let y = base;
  for (const [w, h] of list) { y -= h; R(c, col, cx - (w >> 1), y, w, h); }
}

// гладкий свод/скат с контуром: list снизу вверх [hw, h]; контур edge идёт
// по верхней кромке каждого ряда; ov — нахлёст контура (1 — связная дуга)
function arcRows(c, cx, base, list, body, edge, ov) {
  let y = base; const ys = [];
  for (const [, h] of list) { y -= h; ys.push(y); }
  for (let k = list.length - 1; k >= 0; k--) {
    const [hw, h] = list[k], up = (k + 1 < list.length ? list[k + 1][0] : 0) - ov;
    R(c, edge, cx - hw, ys[k], hw * 2, h);
    if (up > 0) R(c, body, cx - up, ys[k], up * 2, h);
  }
}


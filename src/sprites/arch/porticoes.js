// Великая стена: отдельный склон холма, стена едет по гребню вверх к
// сигнальной башне; над башней караулка под широкой кровлей с загнутыми
// концами; справа — недостроенный край в бамбуковых лесах.
function greatWall(c, X, Y, t) {
  const x0 = q(X), B = q(Y), L = x0 - 48;
  const hh = (x) => x < 48 ? 3 + x * 0.31 : x < 62 ? 18 : Math.max(6, 18 - (x - 62) * 0.6);
  // стена: короткие прясла по склону (низ спрячет холм)
  for (const [a, w] of [[0, 6], [6, 6], [12, 6], [18, 6], [24, 6], [30, 6], [36, 6], [42, 6], [62, 7], [69, 7], [76, 6]]) {
    const top = q(hh(a + w / 2)) + 8;
    R(c, D5, L + a, B - top, w, top); R(c, P, L + a, B - top, w, 1);
    R(c, D5, L + a + 1, B - top - 2, 2, 2);            // зубец
  }
  R(c, D5, L + 48, B - 42, 14, 42);                    // сигнальная башня
  R(c, C1, L + 48, B - 42, 1, 24); R(c, D1, L + 61, B - 42, 1, 24); R(c, P, L + 48, B - 42, 14, 1);
  R(c, N, L + 53, B - 33, 4, 5);
  R(c, D2, L + 50, B - 48, 10, 6);                     // караулка
  const f = ((t || 0) / 20 | 0) % 3;
  R(c, S, L + 54, B - 46 + (f === 1 ? 1 : 0), 2, 2 - (f === 1 ? 1 : 0));   // сигнальный огонь
  const tx = L + 55;                                   // кровля шире башни
  R(c, D1, tx - 10, B - 50, 20, 2); R(c, P, tx - 10, B - 50, 20, 1);
  R(c, P, tx - 12, B - 51, 2, 1); R(c, P, tx - 13, B - 52, 1, 1);  // загнутые концы
  R(c, P, tx + 10, B - 51, 2, 1); R(c, P, tx + 12, B - 52, 1, 1);
  R(c, D1, tx - 7, B - 53, 14, 3); R(c, P, tx - 7, B - 53, 14, 1);
  R(c, D1, tx - 3, B - 54, 6, 1);                      // конёк с рожками
  R(c, P, tx - 4, B - 55, 1, 1); R(c, P, tx + 3, B - 55, 1, 1);
  // холм: отдельная масса, кромка уступами по 1 px
  R(c, D2, L, B - 3, 96, 3);
  for (let k = 3; k < 18; k++) {
    let a = 0; while (hh(a) <= k) a++;
    let b = 95; while (hh(b) <= k) b--;
    R(c, D2, L + a, B - k - 1, b - a + 1, 1);
  }
  R(c, M, L + 14, B - 9, 2, 1); R(c, M, L + 33, B - 15, 3, 1); R(c, M, L + 70, B - 15, 2, 1);
  R(c, D4, L + 84, B - 12, 4, 6); R(c, P, L + 84, B - 12, 4, 1);  // недострой
  R(c, C2, L + 83, B - 30, 1, 24); R(c, C2, L + 89, B - 28, 1, 22); R(c, C2, L + 95, B - 24, 1, 18);
  R(c, C2, L + 82, B - 18, 14, 1); R(c, C2, L + 82, B - 26, 13, 1);
  R(c, B2, L + 86, B - 29, 4, 3); R(c, B2, L + 91, B - 21, 3, 3);   // корзины земли
}

// ── ЗАПАД · Европа, лимес ─────────────────────────────────────────
// ель германского леса: ярусы лап, теневая грань справа
function tree(c, x, base, h) {
  const n = 5, th = q((h - 2) / n);
  for (let k = 0; k < n; k++) {
    const hw = 5 - k, y = base - (k + 1) * th;
    R(c, M, x - hw, y, hw * 2 + 1, th + 1); R(c, D1, x + hw, y + 1, 1, th);
  }
  R(c, M, x, base - h, 1, h - n * th);
}

// Башня лимеса: квадровая кладка, полуциркульные ворота с замковым
// камнем, по сторонам — обрубки каменной куртины с плоским парапетом,

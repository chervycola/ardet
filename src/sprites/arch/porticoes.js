  R(c, C1, cx - 10, B - 50, 1, 43); R(c, D1, cx + 9, B - 50, 1, 43);
  for (const y of [B - 43, B - 36, B - 29, B - 22, B - 15]) R(c, D2, cx - 9, y, 18, 1);  // ряды квадров
  for (const [jx, jy] of [[3, 50], [-4, 43], [5, 36], [-6, 29], [2, 29], [-7, 22], [6, 22]]) R(c, D2, cx + jx, B - jy, 1, 7);
  R(c, N, cx - 1, B - 35, 2, 5);                       // бойница
  R(c, C1, cx - 4, B - 19, 8, 2); R(c, C1, cx - 3, B - 21, 6, 2);   // клинчатые камни
  R(c, K, cx - 1, B - 22, 2, 2);                       // замковый камень
  R(c, N, cx - 3, B - 18, 6, 11); R(c, N, cx - 2, B - 19, 4, 1); R(c, N, cx - 1, B - 20, 2, 1);  // ворота
  const sx = cx + 12;                                  // скутум брошен у ворот
  R(c, D1, sx, B - 8, 6, 8); R(c, D1, sx + 1, B - 10, 6, 2);
  R(c, V, sx + 1, B - 7, 4, 6); R(c, V, sx + 2, B - 9, 4, 2); R(c, G, sx + 2, B - 6, 2, 2);
  R(c, B2, cx - 9, B - 60, 18, 8);                     // деревянный ярус
  R(c, N, cx - 6, B - 59, 3, 4); R(c, N, cx + 3, B - 59, 3, 4);

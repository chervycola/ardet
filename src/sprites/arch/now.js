// ── ДОМИНАНТА · ЮГ ───────────────────────────────────────────────────
// «Линия»: отрезок зеркальной стены во всю рамку. В стекле — ночь и
// пустыня за спиной смотрящего: дюны сепией, гребни пеплом, отражённые
// звёзды; саму стену выдают только верхняя кромка и швы панелей.
// У подножия — забор стройки с воротами и башенный кран, на крюке —
// ещё одна зеркальная панель. Огонь — сигнальный на оголовке крана.
function theLine(c, x, gy, t) {
  const X = Math.round(x), L = X - 70, G = Math.round(gy);
  // лицо стены: стекло, отражающее ночь
  R(c, N, L, G - 148, 140, 148);
  R(c, ASH, L, G - 149, 140, 1); R(c, BONE, L + 22, G - 149, 6, 1);
  for (let k = 1; k < 5; k++) R(c, DARK, L + k * 28, G - 148, 1, 140);
  for (const h of [112, 76]) R(c, DARK, L, G - h, 140, 1);
  // отражённые звёзды
  for (const [sx, sy] of [[9, 131], [37, 119], [58, 138], [93, 127], [121, 135], [133, 116], [74, 101]]) R(c, ASH, L + sx, G - sy, 1, 1);
  // отражённая пустыня: дальние дюны сепией с гребнем пеплом, ближние темнее
  R(c, SEP, L, G - 34, 140, 26);
  for (const [dx, w, h] of [[0, 16, 38], [16, 12, 42], [28, 10, 45], [38, 14, 41], [52, 18, 37], [70, 10, 39], [80, 16, 44], [96, 14, 47], [110, 14, 43], [124, 16, 39]]) {
    R(c, SEP, L + dx, G - h, w, h - 34); R(c, ASH, L + dx, G - h, w, 1);
  }
  R(c, STONE2, L, G - 22, 140, 14);
  for (const [dx, w, h] of [[0, 22, 24], [22, 18, 27], [40, 22, 25], [62, 18, 29], [80, 22, 26], [102, 18, 28], [120, 20, 25]]) {
    R(c, STONE2, L + dx, G - h, w, h - 22); R(c, SEP, L + dx, G - h, w, 1);
  }
  // забор стройки, ворота в рост
  R(c, CONC, L, G - 8, 88, 8); R(c, CONC, L + 108, G - 8, 32, 8);
  R(c, ASH, L, G - 9, 88, 1); R(c, ASH, L + 108, G - 9, 32, 1);
  for (let px = 6; px < 140; px += 12) if (px < 88 || px > 108) R(c, STONE2, L + px, G - 8, 1, 8);
  R(c, N, L + 90, G - 20, 16, 20);
  R(c, ASH, L + 88, G - 22, 2, 22); R(c, ASH, L + 106, G - 22, 2, 22); R(c, ASH, L + 88, G - 22, 20, 1);
  // башенный кран: мачта-решётка, стрела, противовес, оголовок с тягами
  const M = L + 26;
  R(c, ASH, M - 2, G - 72, 1, 64); R(c, ASH, M + 2, G - 72, 1, 64);
  for (let h = 12; h < 72; h += 6) R(c, MIST, M - 1, G - h, 3, 1);
  R(c, DARK, M - 3, G - 8, 7, 1);
  R(c, ASH, M - 18, G - 74, 70, 1); R(c, MIST, M + 2, G - 72, 50, 1);
  for (let jx = M + 6; jx < M + 52; jx += 6) R(c, MIST, jx, G - 73, 1, 1);
  R(c, CONC, M - 18, G - 73, 7, 4); R(c, ASH, M - 18, G - 73, 7, 1);
  R(c, STONE, M - 4, G - 72, 4, 3);
  R(c, ASH, M - 1, G - 84, 2, 10);
  hline(c, ASH, M, G - 84, M + 50, G - 75); hline(c, ASH, M, G - 84, M - 16, G - 75);
  // тележка, трос, на крюке — зеркальная панель
  R(c, ASH, M + 38, G - 73, 3, 1); R(c, ASH, M + 39, G - 72, 1, 26);
  R(c, DARK, M + 33, G - 46, 13, 10); R(c, ASH, M + 33, G - 46, 13, 1); R(c, SEP, M + 33, G - 39, 13, 3);
  // сигнальный огонь на оголовке
  R(c, CANDLE, M - 1, G - 86, 2, 2);
  if (((t | 0) >> 4) % 4) R(c, CANDLE, M, G - 87, 1, 1);
}


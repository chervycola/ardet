function R(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(x, y, w, h); }
// стрельчатый проём: lx — левый край, by — низ, w×h
function PA(c, col, lx, by, w, h) {
  const k = (w - 1) >> 1;
  c.fillStyle = col;
  c.fillRect(lx, by - h + k, w, h - k);
  for (let i = 1; i <= k; i++) c.fillRect(lx + i, by - h + k - i, w - 2 * i, 1);
}
// персидская (четырёхцентровая) арка: шаг 2 px на ряд — площе готической
function PAF(c, col, lx, by, w, h) {
  const k = (w - 2) >> 2;
  c.fillStyle = col;
  c.fillRect(lx, by - h + k, w, h - k);
  for (let i = 1; i <= k; i++) c.fillRect(lx + 2 * i, by - h + k - i, w - 4 * i, 1);
}
// ярусы снизу вверх: ось между cx-1 и cx, hw — полуширины, rh — высота яруса
function TIERS(c, col, cx, by, hw, rh) {
  c.fillStyle = col;
  for (let i = 0; i < hw.length; i++) c.fillRect(cx - hw[i], by - (i + 1) * rh, hw[i] * 2, rh);
}
// ярусы под снегом: тот же силуэт костью на 2 px выше — снег на каждом уступе и шапка
function SNOWTIERS(c, col, cx, by, hw, rh) {
  TIERS(c, BONE, cx, by - 2, hw, rh);
  TIERS(c, col, cx, by, hw, rh);
}
// ряды с кромкой: edge — контур, fill — тело; верхний ряд — сплошной контур
function OUT(c, edge, fill, cx, by, hw, rh) {
  for (let i = 0; i < hw.length; i++) {
    const y = by - (i + 1) * rh;
    R(c, edge, cx - hw[i], y, hw[i] * 2, rh);
    if (i < hw.length - 1 && hw[i] > 1) R(c, fill, cx - hw[i] + 1, y, hw[i] * 2 - 2, rh);
  }
}
// восьмигранное кольцо s×s (линза, циферблат, армилла)
function RING(c, col, inner, lx, ty, s) {
  R(c, col, lx + 1, ty, s - 2, s); R(c, col, lx, ty + 1, s, s - 2);
  if (s >= 6) { R(c, inner, lx + 2, ty + 1, s - 4, s - 2); R(c, inner, lx + 1, ty + 2, s - 2, s - 4); }
  else R(c, inner, lx + 1, ty + 1, s - 2, s - 2);
}
// дуга квадранта: четверть круга r=16 от правого верхнего угла, сжатая в пробеги
const QARC = (() => {
  const r = 16, xs = [], runs = [];
  for (let j = 0; j <= r; j++) xs.push(Math.round(Math.sqrt(r * r - j * j)));
  xs.push(-1);
  for (let j = 0; j <= r; j++) {
    const b = xs[j], a = Math.min(b, Math.max(xs[j + 1] + 1, 0));
    const last = runs[runs.length - 1];
    if (a === b && last && last[2] === 1 && last[0] === -b && last[1] + last[3] === j) last[3]++;
    else runs.push([-b, j, b - a + 1, 1]);
  }
  return runs;
})();
const ph = (t, period, n) => (((t || 0) / period) | 0) % n;


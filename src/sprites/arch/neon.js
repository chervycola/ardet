  // ворота: столбы, решётка, проход — тьма
  R(c, N, X - 13, G - 20, 27, 20);
  R(c, STONE2, X - 16, G - 22, 3, 22); R(c, STONE2, X + 14, G - 22, 3, 22);
  R(c, ASH, X - 16, G - 22, 1, 22); R(c, ASH, X + 16, G - 22, 1, 22);
  for (let k = -2; k <= 2; k++) R(c, ASH, X + k * 5, G - 20, 1, 20);
  // маркиза аркой над воротами: тёмный щит, по кромке — мёртвые лампочки
  for (let dx = -18; dx <= 18; dx++) {
    const top = G - 23 - Math.round(10 * Math.sqrt(1 - (dx / 19) * (dx / 19)));
    R(c, WOOD, X + dx, top, 1, G - 21 - top);
    R(c, ASH, X + dx, top, 1, 1);
    if (dx % 2 === 0 && (dx + 40) % 7 !== 3) R(c, ASH, X + dx, top + 2, 1, 1);
  }
  R(c, ASH, X - 17, G - 22, 35, 1);
  R(c, STONE2, X - 9, G - 28, 19, 3); R(c, N, X - 8, G - 27, 4, 1); R(c, N, X + 1, G - 27, 7, 1);   // доска: буквы осыпались
  // касса «перерыв 30 лет»
  R(c, STONE2, L + 76, G - 14, 9, 14); R(c, ASH, L + 75, G - 15, 11, 1);
  R(c, N, L + 78, G - 11, 5, 4); R(c, PAPER2, L + 79, G - 6, 3, 2);
  // пилон со звездой-гуги: косой стебель, восемь лучей разной длины
  stair(c, CONC, L + 9, G, L + 6, G - 52, 4, 2);

function R(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(x, y, w, h); }

// ступенчатая линия (опоры, ванты, растяжки): от (x0,y0) к (x1,y1) шагами
function stair(c, col, x0, y0, x1, y1, steps, tw = 1) {
  c.fillStyle = col;
  for (let i = 0; i < steps; i++) {
    const xa = Math.round(x0 + (x1 - x0) * i / steps);
    const ya = Math.round(y0 + (y1 - y0) * i / steps);
    const yb = Math.round(y0 + (y1 - y0) * (i + 1) / steps);
    c.fillRect(xa, Math.min(ya, yb), tw, Math.max(1, Math.abs(yb - ya)));
  }
}

// попиксельная прямая (только для кэша): Брезенхем
function line(c, col, x0, y0, x1, y1) {
  c.fillStyle = col;
  const dx = Math.abs(x1 - x0), sx = x0 < x1 ? 1 : -1, dy = -Math.abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
  let err = dx + dy;
  for (;;) {
    c.fillRect(x0, y0, 1, 1);
    if (x0 === x1 && y0 === y1) break;
    const e2 = 2 * err;
    if (e2 >= dy) { err += dy; x0 += sx; }
    if (e2 <= dx) { err += dx; y0 += sy; }
  }
}

// окружность средней точкой (только для кэша): чётко, без сглаживания
function ring(c, col, cx, cy, r) {
  c.fillStyle = col;
  let x = r, y = 0, err = 1 - r;
  while (x >= y) {
    c.fillRect(cx + x, cy + y, 1, 1); c.fillRect(cx + y, cy + x, 1, 1);
    c.fillRect(cx - y, cy + x, 1, 1); c.fillRect(cx - x, cy + y, 1, 1);
    c.fillRect(cx - x, cy - y, 1, 1); c.fillRect(cx - y, cy - x, 1, 1);
    c.fillRect(cx + y, cy - x, 1, 1); c.fillRect(cx + x, cy - y, 1, 1);
    y++;
    if (err < 0) err += 2 * y + 1; else { x--; err += 2 * (y - x) + 1; }
  }
}

// кэш статики: постройка рисуется один раз в свой холст (лениво, на уровне
// модуля), дальше — один drawImage за кадр. Без canvas — рисуем напрямую.
const SPR = {};
function blit(c, key, w, h, paint, L, G) {
  if (!(key in SPR)) {
    let cv = null;
    try {
      if (typeof document !== 'undefined' && document.createElement) {
        cv = document.createElement('canvas'); cv.width = w; cv.height = h;
      } else if (typeof OffscreenCanvas !== 'undefined') cv = new OffscreenCanvas(w, h);
      if (cv) paint(cv.getContext('2d'), 0, h);
    } catch (e) { cv = null; }
    SPR[key] = cv;
  }
  const cv = SPR[key];
  if (cv && typeof c.drawImage === 'function') c.drawImage(cv, L, G - h);
  else paint(c, L, G);
}


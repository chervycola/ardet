// Останкинская башня: бетонный конус на ногах-арках, тонкий ствол с
// поясами техэтажей, обод ресторана, выше — стальная антенна. Огни —
// заградительные, киноварью; верхний мигает.
function ostankino(c, x, gy, t) {
  const X = Math.round(x), G = Math.round(gy);
  // ноги-арки: четыре видимых опоры сходятся к конусу
  for (const [b, top, col] of [[-30, -8, ASH], [-15, -4, CONC], [14, 3, CONC], [29, 7, STONE]]) stair(c, col, X + b, G, X + top, G - 30, 10, 3);
  stair(c, BONE, X - 31, G, X - 9, G - 30, 10, 1);
  // конус
  for (let i = 0; i < 6; i++) { const w = 16 - i * 2; R(c, CONC, X - (w >> 1), G - 30 - i * 5 - 5, w, 5); R(c, BONE, X - (w >> 1), G - 30 - i * 5 - 5, 1, 5); }
  // вход между средними ногами — остеклённое лобби под рост
  R(c, STONE2, X - 6, G - 20, 12, 20); R(c, N, X - 3, G - 19, 6, 19); R(c, ASH, X - 6, G - 20, 12, 1); R(c, ASH, X, G - 19, 1, 19);
  // ствол: сужается ступенями до обода и выше
  const segs = [[60, 80, 5], [80, 102, 4], [102, 124, 4], [124, 134, 3], [134, 150, 3]];
  for (const [a, b, w] of segs) { R(c, CONC, X - (w >> 1) - 1, G - b, w, b - a); R(c, BONE, X - (w >> 1) - 1, G - b, 1, b - a); }
  // пояса техэтажей
  for (const h of [72, 96]) { R(c, ASH, X - 4, G - h, 7, 2); R(c, N, X - 3, G - h + 1, 5, 1); }
  // обод ресторана: три этажа, окна лентой
  R(c, CONC, X - 9, G - 124, 17, 8); R(c, BONE, X - 9, G - 124, 17, 1); R(c, ASH, X - 9, G - 117, 17, 1);
  R(c, N, X - 8, G - 122, 15, 1); R(c, N, X - 8, G - 120, 15, 1);
  R(c, MIST, X - 6, G - 120, 2, 1);                       // в окне — отсвет экрана
  // антенна: стальная мачта ступенями, площадки
  R(c, ASH, X - 2, G - 170, 3, 20); R(c, ASH, X - 1, G - 188, 2, 18); R(c, BONE, X - 1, G - 197, 1, 9);
  for (const h of [158, 170, 182]) R(c, ASH, X - 3, G - h, 5, 1);
  // заградительные огни — киноварью
  R(c, CIN, X - 10, G - 121, 1, 1); R(c, CIN, X + 8, G - 121, 1, 1);
  R(c, CIN, X - 3, G - 171, 1, 1); R(c, CIN, X + 2, G - 171, 1, 1);
  R(c, CIN, X - 1, G - 199, 1, 2);
  if (((t | 0) >> 4) % 3) R(c, CIN, X - 2, G - 199, 3, 1);
}


  r(c, K4, x - 9, g - 19, 3, 17); r(c, BO, x - 9, g - 19, 1, 17);   // анты
  r(c, K4, x + 6, g - 19, 3, 17); r(c, BO, x + 6, g - 19, 1, 17);
  r(c, L2, x - 6, g - 19, 2, 17); r(c, L2, x + 4, g - 19, 2, 17);   // колонны

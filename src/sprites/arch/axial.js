  P.box(pc - 19, 0, 1, 87, MAT.TIMBER); P.box(pc + 18, 0, 1, 87, MAT.TIMBER);   // мачты выше башен
  P.box(pc - 7, 40, 14, 48, MAT.SANDSTONE); P.box(pc - 9, 36, 18, 4, MAT.SANDSTONE);   // портал и его карниз

  const cw = v ? [6, 5, 7, 6, 7, 5] : [6, 6, 6, 6, 6, 6], kw = v ? [8, 6, 9, 8, 7, 7] : [8, 8, 8, 8, 8, 8];
  for (let i = 0; i < 6; i++) {                                             // шесть колонн с каннелюрами, капители
    const lx = tx - 33 + 12 * i + ((6 - cw[i]) >> 1);
    P.box(lx, 29, cw[i], 35, MAT.MARBLE, FORM.FLUTE);
    P.box(lx - ((kw[i] - cw[i]) >> 1), 27, kw[i], 2, MAT.MARBLE);
  }
  P.box(3, 23, 68, 4, MAT.MARBLE);                                          // архитрав
  P.box(3, 18, 68, 5, MAT.MARBLE);                                          // фриз
  for (let i = 0; i < 6; i++) P.box(tx - 32 + 12 * i, 18, 3, 5, MAT.ASHLAR);   // триглифы
  P.box(1, 16, 72, 2, MAT.MARBLE);                                          // карниз

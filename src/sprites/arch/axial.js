  for (let i = 0; i < 5; i++) r(c, AS, x - 5 + 2 * i + (i > 2 ? 1 : 0), g - 17, 1, 9);   // основа
  r(c, BR2, x - 7, g - 13, 14, 1); r(c, K1, x - 7, g - 14, 1, 1); r(c, K1, x + 6, g - 14, 1, 1);   // ремизный пруток на вилках

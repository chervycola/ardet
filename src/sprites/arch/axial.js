// под ним просвет и блюдце подношений.
function shipstones(c, X, G) {
  const W = 92, H = 34, cx = 26, sx = 77;             // ось ладьи и ось сейда — от левого края рамки
  if (!shipstones.P) {
    const P = shipstones.P = plan(W, H);
    // ладья — эллипс камней в ракурсе: дальний борт выше по кадру и мельче, ближний ниже и
    // крупнее; к штевням камни выше (так стоят Алес стенар), внутри — мох
    const cy = 25, A = 22, B = 6, N = 12;
    for (let y = Math.ceil(cy - B); y <= cy + B; y++) {
      const k = 1 - ((y - cy) / B) ** 2, hw = A * Math.sqrt(Math.max(0, k)) - 2;
      if (hw > 0) P.box(q(cx - hw), y, q(hw * 2), 1, MAT.MOSS);
    }
    const st = [];
    for (let i = 0; i < N; i++) {
      const th = Math.PI * 2 * i / N, c0 = Math.cos(th), s0 = Math.sin(th), near = s0 > 0;
      st.push({ bx: cx + A * c0, by: q(cy + B * s0), h: q((near ? 4 : 3) + (near ? 9 : 7) * Math.abs(c0) ** 4), w: near ? 5 : 4 });
    }
    st.sort((a, b) => a.by - b.by);                                          // дальние — раньше
    for (const o of st) P.round(o.bx, o.by - o.h, o.by, o.w, MAT.GRANITE);
    // сейд: валун шире своей высоты лежит на трёх камнях-ножках, левый бок выше; под ним просвет
    P.round(sx - 8, 30, 33, 6, MAT.BASALT); P.round(sx + 1, 31, 33, 4, MAT.BASALT); P.round(sx + 8, 30, 33, 6, MAT.BASALT);
    P.poly([[sx - 13, 30], [sx - 13, 25], [sx - 10, 21], [sx - 4, 19], [sx + 4, 20], [sx + 10, 23], [sx + 13, 27], [sx + 12, 30]], MAT.GRANITE);
  }
  const X0 = q(X) - (W >> 1), Y0 = q(G) - H;
  paint(c, X0, Y0, shipstones.P, { seed: 5, snow: 0.55, moss: 0.25, chip: 0.05, ao: 1 });
  r(c, AS, X0 + sx + 1, Y0 + 33, 3, 1); r(c, BO, X0 + sx + 2, Y0 + 32, 1, 1);   // блюдце, монета
}


  P.trap(pc - 41, pc - 8, pc - 30, pc - 8, 16, 87, MAT.SANDSTONE);           // башни: откос наружу,
  P.trap(pc + 8, pc + 40, pc + 8, pc + 29, 16, 87, MAT.SANDSTONE);           // внутренний край отвесный
  P.box(pc - 32, 12, 25, 4, MAT.SANDSTONE); P.box(pc + 7, 12, 26, 4, MAT.SANDSTONE);   // карнизы-выкружки

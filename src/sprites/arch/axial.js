// отрезок ступеньками [x0, x1): пологий — по рядам, крутой — по столбцам
function seg(c, col, x0, y0, x1, y1) {
  const dx = x1 - x0, dy = y1 - y0;
  if (Math.abs(dx) >= Math.abs(dy)) {
    const n = Math.abs(dy) + 1, s = Math.sign(dy);
    for (let k = 0; k < n; k++) {
      const a = x0 + q(dx * k / n), b = x0 + q(dx * (k + 1) / n);
      r(c, col, Math.min(a, b), y0 + s * k, Math.max(1, Math.abs(b - a)), 1);
    }
  } else {
    const n = Math.abs(dx) + 1, s = Math.sign(dx);
    for (let k = 0; k < n; k++) {
      const a = y0 + q(dy * k / n), b = y0 + q(dy * (k + 1) / n);
      r(c, col, x0 + s * k, Math.min(a, b), 1, Math.max(1, Math.abs(b - a)));
    }
  }
}

// Ярусная масса с кромкой по всему контуру: свет (lit) слева и сверху,
// кромка (rim) справа до самой подошвы. rows — снизу вверх: [влево, вправо, высота]
// от оси cx; g — низ первого яруса. Возвращает верх массы (контур — на 1 выше).
function mass(c, cx, g, rows, body, lit, rim) {
  let y = g, e = 1;
  for (const [L, R, h] of rows) {
    y -= h;
    r(c, rim, cx - L + 1, y - 1, L + R, h + e);
    r(c, lit, cx - L - 1, y - 1, L + R, h + e);
    r(c, body, cx - L, y, L + R, h);
    e = 0;
  }
  return y;
}


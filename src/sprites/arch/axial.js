// Петроглиф: плоский выход ледниковой скалы вровень с дёрном, на нём выбита ладья
// бронзового века — киль шпорой за оба штевня («вилки» на концах), над корпусом черточки
// гребцов, без вёсел и паруса; рядом две чашечные ямки. Желобки тёмные; красной краски нет
// (в Тануме её наносят теперь).
function petroglyph(c, X, G) {
  const x = q(X), g = q(G);
  r(c, AS, x - 7, g - 4, 15, 4); r(c, AS, x - 8, g - 3, 17, 2);                // скала
  r(c, L2, x - 6, g - 4, 13, 1); r(c, K3, x - 8, g - 1, 17, 1);                // верх к свету, край уходит в дёрн
  r(c, MG, x - 8, g - 2, 2, 1); r(c, MG, x + 7, g - 2, 2, 1);                  // дёрн на краях
  r(c, K1, x - 5, g - 2, 11, 1);                                               // киль
  r(c, K1, x - 4, g - 3, 1, 1); r(c, K1, x + 4, g - 3, 1, 1);                  // штевни: вилки
  for (const dx of [-2, 0, 2]) r(c, K1, x + dx, g - 3, 1, 1);                  // гребцы
  r(c, K1, x - 7, g - 3, 1, 1); r(c, K1, x + 6, g - 4, 1, 1);                  // чашечные ямки
}

// Вешало с рыбой (за вежей — изнанка): два кола с развилкой, жердь в рост, три пары рыб
// хвостами через жердь, низ темнее. Пары качаются по ветру целиком, на точку, медленно, не
// касаясь друг друга. Для эпохи — по аналогии: так сушат и теперь.
function fishRack(c, X, G) {
  const x = q(X), g = q(G);
  r(c, K1, x - 7, g - 11, 1, 11); r(c, K1, x + 6, g - 11, 1, 11); r(c, L2, x - 7, g - 11, 1, 11);   // колья
  r(c, K1, x - 8, g - 12, 1, 1); r(c, K1, x - 6, g - 12, 1, 1); r(c, K1, x + 5, g - 12, 1, 1); r(c, K1, x + 7, g - 12, 1, 1);   // развилки
  r(c, BR2, x - 7, g - 11, 14, 1); r(c, L2, x - 7, g - 11, 14, 1);             // жердь
  [-4, 0, 4].forEach((fx, i) => {
    const px = x + fx, b = hang(`fish:${x}:${g}:${i}`, px, g - 10, 5, { sail: 0.015, damp: 0.994, gy: g });
    const sw = Math.max(-1, Math.min(1, Math.round(Math.sin(angleOf(b)) * 3)));
    r(c, K3, px, g - 10, 1, 1);                                                // хвосты связаны
    r(c, L2, px - 1, g - 9, 1, 2); r(c, K3, px + 1, g - 9, 1, 2);              // передняя и задняя
    r(c, L2, px - 1 + sw, g - 7, 1, 1); r(c, K3, px + 1 + sw, g - 7, 1, 1);
    r(c, K1, px - 1 + sw, g - 6, 1, 1); r(c, K1, px + 1 + sw, g - 6, 1, 1);    // низ темнее
  });
}


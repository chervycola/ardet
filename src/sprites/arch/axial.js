// ── ДОМИНАНТА · юг ─────────────────────────────────────────────────
// Зиккурат Этеменанки (Вавилон, Набопаласар и Навуходоносор II): шесть
// уступов сырцовой массы, пояса камышовых циновок, ниши-лопатки по нижнему
// ярусу; главная лестница с юга в лоб, у подножия ворота в рост; выше —
// узкий марш до храма. Наверху храм с зубцами, в дверях — светильник.
function etemenanki(c, X, G, t) {
  const x = q(X), g = q(G);
  const T = [[74, 32], [60, 26], [48, 22], [38, 18], [29, 15], [21, 13]];
  const top = mass(c, x, g, T.map(([w, h]) => [w, w, h]), K2, L2, AS);
  let y = g;
  for (let i = 0; i < T.length; i++) {                // пояса циновок, тень под уступом
    const [w, h] = T[i];
    y -= h;
    r(c, K1, x - w, y + q(h / 2), w * 2, 1);
    if (i < T.length - 1) r(c, K0, x - w, y + 1, w * 2, 1);
  }
  for (let k = -66; k <= 66; k += 12) if (Math.abs(k) > 12) r(c, K3, x + k, g - 30, 3, 30); // лопатки
  r(c, K3, x - 9, g - 58, 18, 58);                     // главная лестница
  r(c, L2, x - 9, g - 58, 1, 58); r(c, AS, x + 8, g - 58, 1, 58);
  for (let s = g - 26; s > g - 58; s -= 3) r(c, K1, x - 8, s, 16, 1);
  r(c, K1, x - 12, g - 26, 24, 26);                   // ворота у подножия
  r(c, L2, x - 12, g - 26, 1, 26); r(c, AS, x + 11, g - 26, 1, 26);
  r(c, L2, x - 12, g - 27, 24, 1);
  for (const o of [-12, -6, 0, 6]) r(c, K1, x + o + 1, g - 29, 4, 2);
  r(c, NI, x - 4, g - 21, 8, 21); r(c, NI, x - 3, g - 22, 6, 1);
  const m0 = g - 58, m1 = top;                        // узкий марш выше
  r(c, K3, x - 3, m1, 6, m0 - m1);
  r(c, L2, x - 3, m1, 1, m0 - m1);
  for (let s = m0 - 3; s > m1; s -= 3) r(c, K1, x - 2, s, 4, 1);
  // храм наверху: сырец под зубцами, дверь, светильник
  const tb = top;
  r(c, AS, x - 14, tb - 19, 29, 19); r(c, L2, x - 15, tb - 19, 29, 19);
  r(c, K3, x - 14, tb - 18, 28, 18);
  for (const o of [-14, -8, -2, 4, 10]) { r(c, K3, x + o, tb - 22, 4, 3); r(c, L2, x + o, tb - 22, 4, 1); }
  r(c, K2, x - 10, tb - 14, 1, 14); r(c, K2, x + 9, tb - 14, 1, 14);
  r(c, NI, x - 3, tb - 12, 6, 12);
  const f = ((t || 0) / 16 | 0) % 3;
  r(c, CA, x - 2, tb - 6 + (f === 1 ? 1 : 0), 4, 4 - (f === 1 ? 1 : 0));
  r(c, CA, x - 1 + (f === 2 ? 1 : 0), tb - 8, 2, 2);
}


// ═══ АРХИТЕКТУРА · три огня (осевое время, ~VIII–III вв. до н. э.) ═══
// Одна эпоха — пять культур. Юг: пилон с обелиском и дорический храм на
// египетском фундаменте (блок со знаками положен вверх ногами, рядом лежит
// пифос Диогена). Восток: застава Ханьгу — глинобитная башня в ущелье, будка
// Инь Си — и ступа с тораной. Запад: низкий кельтский круглый дом под широкой
// соломой и святилище с черепами в нишах (Рокпертюз) у дуба с омелой.
// Север: каменная ладья с сейдом, дерновая вежа и бубен-карта на шесте.
// Равнина: курган с каменной бабой и скифская кибитка у тёплого кострища.
// Свет лунный, слева; у крупных масс справа кромка пеплом — ночью держится.
// Контракт: x — центр, gy — линия земли; рисунок строго в w×h.

const NI = '#0D0B0A', BO = '#D9CFB8', AS = '#8A8D8F', MG = '#3D4A3A';
const CA = '#E28A3A', CI = '#C23B2B';
const K0 = '#15100c', K1 = '#241c14', K2 = '#2a2620', K3 = '#34302a', K4 = '#3a3328';
const BR2 = '#3a2818', DRD = '#3a1c14', GD = '#b8860b';
const L1 = '#c8b89a', L2 = '#b0a284';

function r(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(x, y, w, h); }
const q = Math.round;

// Ярусная масса с кромкой по всему контуру: свет (lit) слева и сверху,
// кромка (rim) справа до самой подошвы. rows — снизу вверх: [влево, вправо, высота]
// от оси cx; g — низ первого яруса. Возвращает верх массы (контур — на 1 выше).
function mass(c, cx, g, rows, body, lit, rim) {
  let y = g, e = 1;
  for (const [L, R, h] of rows) {
    y -= h;
    r(c, rim, cx - L + 1, y - 1, L + R, h + e);
    r(c, lit, cx - L - 1, y - 1, L + R, h + e);
    r(c, body, cx - L, y, L + R, h);
    e = 0;
  }
  return y;
}

// ── ЮГ · древние пути ──────────────────────────────────────────────
// Пилон Эдфу: две скошенные башни выше человека втрое, карниз-выкружка,
// мачты из ниш выше башен, вымпелы; ворота с крылатым диском.
// Слева обелиск: сплошное сужение и золочёный пирамидион.
function pylon(c, X, G) {
  const x = q(X), g = q(G);
  const ox = x - 42;                                   // обелиск
  r(c, K2, ox - 6, g - 3, 12, 3); r(c, L2, ox - 6, g - 3, 12, 1);
  const OB = [[-4, 8], [-3, 7], [-3, 6], [-2, 5]];
  for (let k = 0; k < 4; k++) {
    const [dx, w] = OB[k], y = g - 21 - 18 * k;
    r(c, K3, ox + dx, y, w, 18); r(c, BO, ox + dx, y, 1, 18);
  }
  r(c, GD, ox - 2, g - 76, 5, 1); r(c, GD, ox - 1, g - 78, 3, 2); r(c, GD, ox, g - 79, 1, 1);
  r(c, BO, ox - 2, g - 76, 1, 1); r(c, BO, ox - 1, g - 78, 1, 2);
  r(c, K1, ox, g - 68, 1, 3); r(c, K1, ox - 1, g - 60, 2, 1); r(c, K1, ox, g - 52, 1, 2);
  const pc = x + 7;                                    // ось пилона
  const IN = [0, 2, 3, 5, 6, 8, 9, 11];
  for (let i = 0; i < 8; i++) {                        // башни с откосом
    const y = g - 9 * (i + 1), w = 34 - IN[i];
    r(c, K2, pc - 7 - w, y, w, 9); r(c, L2, pc - 7 - w, y, 1, 9);
    r(c, K2, pc + 7, y, w, 9); r(c, AS, pc + 6 + w, y, 1, 9);
  }
  r(c, K1, pc - 32, g - 76, 26, 4); r(c, BO, pc - 32, g - 76, 26, 1);  // карнизы-выкружки
  r(c, K1, pc + 6, g - 76, 26, 4); r(c, BO, pc + 6, g - 76, 26, 1);
  r(c, K0, pc - 30, g - 44, 1, 5); r(c, K0, pc - 27, g - 40, 1, 5);    // рельеф: знаки
  r(c, K0, pc + 24, g - 44, 1, 5); r(c, K0, pc + 27, g - 40, 1, 5);
  const m1 = pc - 19, m2 = pc + 18;                    // ниши и мачты выше башен
  r(c, NI, m1 - 1, g - 72, 3, 72); r(c, NI, m2 - 1, g - 72, 3, 72);
  r(c, AS, m1, g - 88, 1, 87); r(c, AS, m2, g - 88, 1, 87);
  for (const y of [g - 64, g - 46]) { r(c, BO, m1 - 1, y, 3, 1); r(c, BO, m2 - 1, y, 3, 1); }
  r(c, CI, m1 + 1, g - 88, 3, 1); r(c, CI, m1 + 1, g - 87, 2, 1);    // вымпел
  r(c, L1, m2 + 1, g - 88, 1, 5);                      // лента
  r(c, K3, pc - 7, g - 48, 14, 48); r(c, L2, pc - 7, g - 48, 1, 48); // портал
  r(c, K1, pc - 9, g - 52, 18, 4); r(c, BO, pc - 9, g - 52, 18, 1);
  r(c, NI, pc - 4, g - 40, 8, 40);
  r(c, AS, pc - 6, g - 45, 12, 1); r(c, BO, pc - 1, g - 46, 2, 2);  // крылатый диск
}

// Дорический храм-гексастиль на египетском фундаменте: в кладке — блок со
// знаками, анх петлёй вниз (положен вверх ногами); справа лежит пифос Диогена.

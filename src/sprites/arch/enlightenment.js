// Великая пирамида (набором), какой её обмеряла комиссия для «Описания Египта»: облицовки нет —
// ступени рядами блоков, вершины нет — площадка, на ней полосатая вешка землемера с флажком. Левая
// грань в свету, правая в тени; по теневой грани леса — стойки, настилы, раскосы, приставная лестница
// с земли; на верхней стойке фонарь учёных (живое — слоем поверх). Вход над основанием — лаз под
// двускатной перемычкой. У подножия на лунной стороне — теодолит на треноге; у основания осыпь.
// Надпись стены SCOPERTA DA G. BELZONI · 2. MAR. 1818 — монтаж назван: она во входе пирамиды Хафра,
// открытом Бельцони 2.III.1818, на двадцать лет позже комиссии, — из тех, «кто пришёл позже».
const PYR_ROWS = 25;
const pyramidBody = kit('pyramid', 160, 140, P => {
  for (let i = 0; i < PYR_ROWS; i++) {
    const hw = 77 - i * 3, y = 139 - 4 * (i + 1);
    P.box(80 - hw, y, hw, 4, MAT.SANDSTONE);                                         // грань к свету
    P.box(80, y, hw, 4, MAT.SANDSTONE).shade(2);                                     // грань в тени
  }
  P.cut(77, 117, 6, 7); P.wedge(80, 113, 117, 2, 10, MAT.SANDSTONE);                  // вход под перемычкой
  P.poly([[0, 140], [6, 136], [20, 137], [40, 138], [80, 139], [120, 138], [150, 136], [160, 137], [160, 140]], MAT.SAND).shade(-1);
  for (const [bx, by, bw] of [[10, 135, 4], [24, 136, 3], [140, 134, 5], [150, 135, 3]]) P.box(bx, by, bw, 2, MAT.SANDSTONE);   // осыпь
  // леса по теневой грани: стойки и настилы
  for (const [px, top] of [[136, 101], [124, 86], [112, 71], [100, 56]]) { P.box(px, top, 1, 22, MAT.TIMBER); P.box(px - 11, top - 1, 13, 1, MAT.BOARD); }
  P.box(18, 120, 8, 2, MAT.IRON); P.box(21, 117, 2, 3, MAT.IRON);                    // теодолит
}, { seed: 506, chip: 0.03 }, (c, X0, Y0) => {
  const G = tone(MAT.SANDSTONE, 5), RIM2 = tone(MAT.SANDSTONE, 1);
  for (let i = 0; i < PYR_ROWS; i++) { const hw = 77 - i * 3, y = 139 - 4 * (i + 1); R(c, G, X0 + 80 - hw, Y0 + y, 1, 4); R(c, G, X0 + 80 - hw, Y0 + y, 3, 1); }   // ступени к свету
  R(c, RIM2, X0 + 80, Y0 + 39, 1, 100);                                                // ребро граней
  R(c, G, X0 + 75, Y0 + 39, 5, 1);                                                    // площадка вершины
  // вешка землемера: полосы киноварь — кость
  for (let y = 10; y < 39; y++) R(c, ((y - 10) >> 2) & 1 ? K : B, X0 + 79, Y0 + y, 2, 1);
  // раскосы лесов и приставная лестница с земли
  for (const [ax, ay, bx, by] of [[136, 101], [124, 86], [112, 71]].map((p, k, a) => [p[0], p[1] + 20, [124, 112, 100][k], [86, 71, 56][k] - 1])) hline(c, tone(MAT.TIMBER, 2), X0 + ax, Y0 + ay, X0 + bx, Y0 + by);
  for (let j = 0; j < 4; j++) {
    R(c, tone(MAT.TIMBER, 4), X0 + 148 - 2 * j, Y0 + 130 - 10 * j, 1, 10); R(c, tone(MAT.TIMBER, 4), X0 + 152 - 2 * j, Y0 + 130 - 10 * j, 1, 10);
    R(c, tone(MAT.TIMBER, 3), X0 + 148 - 2 * j, Y0 + 135 - 10 * j, 5, 1); R(c, tone(MAT.TIMBER, 3), X0 + 148 - 2 * j, Y0 + 131 - 10 * j, 5, 1);
  }
  // теодолит: тренога
  hline(c, tone(MAT.TIMBER, 3), X0 + 21, Y0 + 122, X0 + 17, Y0 + 139); hline(c, tone(MAT.TIMBER, 3), X0 + 22, Y0 + 122, X0 + 26, Y0 + 139); R(c, tone(MAT.TIMBER, 3), X0 + 21, Y0 + 122, 1, 17);
  // фонарь учёных: кронштейн на верхней стойке
  R(c, tone(MAT.IRON, 3), X0 + 100, Y0 + 51, 4, 1); R(c, tone(MAT.IRON, 3), X0 + 100, Y0 + 52, 1, 1);
  R(c, tone(MAT.IRON, 1), X0 + 99, Y0 + 53, 3, 1);
});
function pyramidLive(c, x, gy, t) {
  const X0 = Math.round(x) - 80, Y0 = Math.round(gy) - 140, T = t || 0;
  R(c, C, X0 + 99, Y0 + 54, 3, 3);                                                    // фонарь учёных
  if (((T / 11) | 0) % 4 === 1) R(c, S, X0 + 101, Y0 + 56, 1, 1);                     // фитиль чадит
}
const pyramidScaffold = split(pyramidBody, pyramidLive);


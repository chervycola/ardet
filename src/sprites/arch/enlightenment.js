// три полосы письма: знаки — точками, скоропись — частыми штрихами, греческий — строками
function threeHands(c, x0, y0, w, h) {
  const L = mix9(tone(MAT.GRANITE, 4), N, 0.25), t = Math.floor(h / 3);
  for (let y = 1; y < t; y += 2) for (let x = 1; x < w - 1; x += 2) if (noise(x, y, w) > 0.35) R(c, L, x0 + x, y0 + y, 1, 1);
  for (let y = t + 1; y < 2 * t; y += 2) for (let x = 1; x < w - 1; x++) if (noise(x, y, h) > 0.45) R(c, L, x0 + x, y0 + y, 1, 1);
  for (let y = 2 * t + 1; y < h - 1; y += 2) R(c, L, x0 + 1, y0 + y, w - 2 - (y % 3), 1);
}

//          растёт рябина, щиты через один костью и пеплом, счёт не доведён.
// равнина — берестяной свет: белокаменный храм с закомарами и шлемом,
//          в проёме — золото иконы, единственное на равнине; псковская
//          звонница-стена: проём вечевого колокола пуст, с перекладины
//          верёвка до помоста; мостовая ярусами брёвен.
// Утварь дворов (props) — по три вещи на сторону, без осмотра.
// Фасады табличек: андалусский дом с мерлонами и ажимесом, дзэн-мастерская

function R(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(x, y, w, h); }
// стрельчатый проём: lx — левый край, by — низ, w×h
function PA(c, col, lx, by, w, h) {
  const k = (w - 1) >> 1;
  c.fillStyle = col;
  c.fillRect(lx, by - h + k, w, h - k);
  for (let i = 1; i <= k; i++) c.fillRect(lx + i, by - h + k - i, w - 2 * i, 1);
}
// подковообразный проём: косяки шириной w, дуга шире косяков на пиксель
function HS(c, col, lx, by, w, h) {
  c.fillStyle = col;
  c.fillRect(lx + 1, by - h, w - 2, 1);
  c.fillRect(lx, by - h + 1, w, 1);
  c.fillRect(lx - 1, by - h + 2, w + 2, 2);
  c.fillRect(lx, by - h + 4, w, h - 4);
}
// полуциркульный проём
function RA(c, col, lx, by, w, h) {
  c.fillStyle = col;
  c.fillRect(lx + 1, by - h, w - 2, 1);
  c.fillRect(lx, by - h + 1, w, h - 1);
}
// ярусы снизу вверх: ось между cx-1 и cx, hw — полуширины, rh — высота яруса
function TIERS(c, col, cx, by, hw, rh) {
  c.fillStyle = col;
  for (let i = 0; i < hw.length; i++) c.fillRect(cx - hw[i], by - (i + 1) * rh, hw[i] * 2, rh);
}
// восьмигранное кольцо s×s (роза, окулюс)
function RING(c, col, inner, lx, ty, s) {
  R(c, col, lx + 1, ty, s - 2, s); R(c, col, lx, ty + 1, s, s - 2);
  R(c, inner, lx + 2, ty + 1, s - 4, s - 2); R(c, inner, lx + 1, ty + 2, s - 2, s - 4);
}
// диагональ ступеньками 2×2 (раскос, шея дракона): dx, dy — ±1
function DIAG(c, col, x0, y0, n, dx, dy) {
  c.fillStyle = col;
  for (let i = 0; i < n; i++) c.fillRect(x0 + i * dx * 2, y0 + i * dy * 2, 2, 2);
}

// отрезок ступеньками [x0, x1): пологий — по рядам, крутой — по столбцам
function SEG(c, col, x0, y0, x1, y1) {
  const dx = x1 - x0, dy = y1 - y0;
  if (Math.abs(dx) >= Math.abs(dy)) {
    const n = Math.abs(dy) + 1, s = Math.sign(dy);
    for (let k = 0; k < n; k++) {
      const a = x0 + Math.round(dx * k / n), b = x0 + Math.round(dx * (k + 1) / n);
      R(c, col, Math.min(a, b), y0 + s * k, Math.max(1, Math.abs(b - a)), 1);
    }
  } else {
    const n = Math.abs(dx) + 1, s = Math.sign(dx);
    for (let k = 0; k < n; k++) {
      const a = y0 + Math.round(dy * k / n), b = y0 + Math.round(dy * (k + 1) / n);
      R(c, col, x0 + s * k, Math.min(a, b), 1, Math.max(1, Math.abs(b - a)));
    }
  }
}


  const xl = y => 31 + Math.round((y - 9) * 1.5);
  for (let k = 0; k < 13; k++) {
    const y0 = 9 + 2 * k, L = xl(y0) + 2;
    const R = Math.min(xl(y0) + 28, 75 + Math.round((33 - y0) * 0.75));
    f(D1, L, y0 + 1, R - L, 2);
  }
  for (let y = 9; y <= 34; y++) f(B, xl(y), y, 2, 1);
  f(null, 70, 35, 5, 1);
  // кольца ржавчины по срезу воды
  f(RB, 34, 10, 22, 1); f(RR, 37, 12, 22, 1);
  // гюйсшток на форштевне — тоже под углом
  f(A, 75, 38, 1, 3); f(null, 74, 41, 1, 3);
  // клюз, птицы на нём, якорная цепь отвесно в воду
  f(N, 75, 33, 2, 2);
  f(P1, 74, 34, 2, 1); f(null, 78, 35, 1, 1);
  f(A, 76, 31, 1, 23);
  // «Килрой был здесь» — мелом на обшивке носа
  f(P2, 61, 23, 11, 1);
  f(null, 64, 27, 5, 1); f(null, 63, 26, 1, 3); f(null, 69, 26, 1, 3);
  f(null, 65, 25, 1, 1); f(null, 67, 25, 1, 1);

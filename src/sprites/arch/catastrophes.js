// перо: f(цвет|null, dx от левого края, dy — высота верха над землёй, w, h вниз)
function pen(ctx, x, gy, w) {
  const L = Math.round(x - w / 2), G = Math.round(gy);
  return (c, dx, dy, ww, hh) => { if (c) ctx.fillStyle = c; ctx.fillRect(L + dx, G - dy, ww, hh); };
}
// ступенчатая почти-вертикаль: от (dx0, dy0) вверх к (dx1, dy1); w — толщина,
// st — шаг по колонкам (2 — вдвое меньше прямоугольников для пологих раскосов)
function slope(f, c, dx0, dy0, dx1, dy1, w = 1, st = 1) {
  const n = Math.floor(Math.abs(dx1 - dx0) / st) + 1, s = Math.sign(dx1 - dx0) * st, hh = (dy1 - dy0) / n;
  f(c, dx0, Math.round(dy0 + hh), w, Math.round(hh));
  for (let i = 1; i < n; i++) {
    const a = Math.round(dy0 + hh * i), b = Math.round(dy0 + hh * (i + 1));
    f(null, dx0 + s * i, b, w, b - a);
  }
}

// ───────────────────────── ЮГ ─────────────────────────
// затопленный фарватер: нос блокшипа поперёк канала; проход закрыт.
// Воду канала рисует двор (полоса моря с пеной) — здесь только корпус
// по ватерлинию у самой земли и рябь у бортов
function sunkenFairway(ctx, x, gy) {
  const f = pen(ctx, x, gy, 92);
  // нос задран на ~34°: корпус полосами по две строки вдоль палубы; справа
  // его срезают киль (параллельно палубе) и форштевень
  const xl = y => 26 + Math.round((y - 2) * 1.5);
  const stem = y => 79 + Math.round((35 - y) * 0.65);
  for (let y0 = 1; y0 <= 34; y0 += 2) {
    const L = xl(y0) + 2, R = Math.min(xl(y0) + 30, stem(y0));
    if (R > L) f(D1, L, y0 + 1, R - L, 2);
  }
  for (let y = 1; y <= 35; y++) f(B, xl(y), y, 2, 1);
  // кольца ржавчины по срезу воды
  f(RB, 31, 4, 26, 1); f(RR, 34, 6, 24, 1);
  // гюйсшток на форштевне — тоже под углом
  f(A, 77, 38, 1, 3); f(null, 76, 41, 1, 3);
  // клюз, птицы на палубе у носа, якорная цепь отвесно в воду
  f(N, 78, 31, 2, 2);
  f(P1, 73, 35, 2, 1); f(null, 70, 33, 1, 1);
  f(A, 79, 29, 1, 27);
  // рябь у бортов и у цепи
  f(A, 58, 2, 4, 1); f(null, 66, 1, 5, 1); f(null, 77, 1, 5, 1); f(null, 86, 2, 4, 1);
  // «Килрой был здесь» — мелом на обшивке носа
  f(P2, 62, 20, 11, 1);
  f(null, 65, 24, 5, 1); f(null, 64, 23, 1, 3); f(null, 70, 23, 1, 3);
  f(null, 66, 22, 1, 1); f(null, 68, 22, 1, 1);
  f(null, 67, 21, 1, 4);
  f(null, 63, 21, 1, 1); f(null, 71, 21, 1, 1);
  // набережная: каменная одежда, шов, кромка к воде
  f(D5, 0, 12, 28, 12); f(P2, 0, 12, 28, 1); f(N, 0, 7, 28, 1); f(A, 27, 11, 1, 11);
  // кнехты
  f(D1, 2, 14, 3, 2); f(null, 8, 14, 3, 2); f(null, 24, 14, 3, 2);
  f(A, 1, 15, 5, 1); f(null, 7, 15, 5, 1); f(null, 23, 15, 5, 1);
  // шлагбаум «проход закрыт»: стойка, противовес, стрела — две красные полосы
  f(D1, 16, 30, 2, 18); f(A, 18, 30, 1, 18);
  f(D1, 11, 29, 5, 4);
  f(B, 18, 28, 33, 2);
  f(K, 25, 28, 4, 2); f(null, 38, 28, 4, 2);
  // почтовый ящик у подножия — стоячее время шлёт письма
  f(K, 19, 20, 4, 4); f(N, 20, 19, 2, 1); f(D1, 20, 16, 2, 4);
}

// тёмная вышка сороковых в дюне, факел попутного газа, пальма
function flareDerrick(ctx, x, gy, t) {
  const f = pen(ctx, x, gy, 72);
  // дюна, наметённая к ногам вышки; гребень песком
  f(D5, 0, 4, 58, 4); f(null, 14, 7, 34, 3);
  f(P2, 14, 7, 34, 1); f(null, 0, 4, 14, 1);
  // пальма: ствол дугой с лунной кромкой, крона — по три листа вниз,
  // верх листьев в лунном блике (иначе — антенна)
  f(D1, 4, 18, 1, 15); f(P2, 5, 18, 1, 15);
  f(D1, 5, 32, 1, 14); f(P2, 6, 32, 1, 14);
  f(D1, 6, 44, 1, 12); f(P2, 7, 44, 1, 12);
  f(M, 2, 47, 5, 1); f(null, 1, 46, 1, 3);
  f(null, 0, 45, 6, 1); f(null, 0, 44, 1, 4);
  f(null, 3, 43, 3, 1); f(null, 2, 42, 1, 3);
  f(null, 8, 47, 5, 1); f(null, 13, 46, 1, 3);
  f(null, 8, 45, 7, 1); f(null, 15, 44, 1, 4);
  f(null, 8, 43, 4, 1); f(null, 12, 42, 1, 3);
  f(A, 2, 47, 4, 1); f(null, 9, 47, 4, 1); f(null, 0, 45, 2, 1); f(null, 13, 45, 2, 1);
  // буровая вышка: тёмные ноги, кромки пеплом с обеих сторон
  slope(f, D1, 22, 7, 28, 74, 2);
  slope(f, D1, 43, 7, 37, 74, 2);
  slope(f, A, 21, 7, 27, 74);
  slope(f, A, 45, 7, 39, 74);
  const l = dy => Math.round(22 + 6 * (dy - 7) / 67), r = dy => Math.round(44 - 6 * (dy - 7) / 67);
  for (const dy of [25, 40, 57]) { f(D1, l(dy), dy, r(dy) - l(dy), 2); f(A, l(dy), dy + 1, r(dy) - l(dy), 1); }
  // крестовые раскосы нижних пролётов (от пола до пояса 40)
  slope(f, D1, 24, 10, 39, 40, 2, 2); slope(f, D1, 41, 10, 26, 40, 2, 2);
  // кронблок без шпиля, пол буровой
  f(D1, 27, 78, 13, 4); f(B, 27, 78, 13, 1);
  f(D1, 18, 10, 30, 3); f(A, 18, 10, 30, 1);
  // труба на низких опорах — от вышки к факелу
  f(D1, 48, 6, 13, 2); f(A, 48, 6, 13, 1);
  f(D1, 52, 4, 1, 3); f(null, 57, 4, 1, 3);
  // факельный ствол
  f(D1, 60, 58, 3, 54); f(A, 62, 58, 1, 54);
  // пламя: два рваных языка по ветру, никто не зажигал, никто не тушит
  const j = ((t >> 4) % 7 === 0) ? 1 : 0;
  f(C, 59, 61, 3, 3); f(null, 60, 64, 2, 3); f(null, 61 + j, 66, 1, 2);
  f(null, 63, 63, 1, 3); f(null, 64, 65, 1, 2);
  // чёрный шлейф от кончика пламени, сносит ветром
  const s = Math.round(Math.sin(t * 0.02));
  f(N, 61, 70, 2, 4); f(null, 62, 74, 3, 4);
  f(null, 63 + s, 78, 4, 4); f(null, 64 + s, 82, 5, 4); f(null, 65 + 2 * s, 85, 4, 3);
}


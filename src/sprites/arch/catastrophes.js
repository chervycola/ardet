function palaceLive(c, x, gy, t) {
  const X0 = Math.round(x) - 55, Y0 = Math.round(gy) - 198, T = t || 0;
  const night = skyAt(phaseAt(T)).name === 'ночь', w = wind.at(x, gy);
  c.fillStyle = B;
  for (let i = 0; i < 10; i++) {
    const age = (T * 0.35 + i * 17) % 170, k = age / 170, sz = 2 + Math.floor(k * 5);
    const px = X0 + 73 + Math.round(w.x * age * 0.25 + Math.sin(age * 0.06 + i) * 2 * k) - (sz >> 1);
    const py = Y0 + 190 - Math.round(age * 0.32) - (sz >> 1);
    if (py < Y0 + 120) continue;
    c.globalAlpha = (night ? 0.35 : 0.22) * (1 - k);
    c.fillRect(Math.max(X0, Math.min(X0 + 110 - sz, px)), py, sz, sz);
  }
  if (night) {
    for (let y = 49; y >= 0; y--) {
      const k = (49 - y) / 49, bw = 3 + Math.round(k * 4);
      c.globalAlpha = 0.2 - 0.08 * k;
      c.fillRect(X0 + 55 - (bw >> 1), Y0 + y, bw, 1);
    }
  }
  c.globalAlpha = 1;
}

// ── набор (kit.js): прямоугольник краской, шум, пологая линия, смесь красок канона ──
function R(c, col, x, y, w, h) { c.fillStyle = col; c.fillRect(x, y, w, h); }
function noise(i, j, s) {
  let h = (i * 374761393 + j * 668265263 + s * 2246822519) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
function hline(c, col, x0, y0, x1, y1) {
  c.fillStyle = col;
  const n = Math.abs(y1 - y0) + 1, sy = Math.sign(y1 - y0);
  for (let i = 0; i < n; i++) {
    const xa = Math.round(x0 + (x1 - x0) * i / n), xb = Math.round(x0 + (x1 - x0) * (i + 1) / n);
    c.fillRect(Math.min(xa, xb), y0 + sy * i, Math.max(1, Math.abs(xb - xa)), 1);
  }
}
function mix9(a, b, k) {
  const p = v => [1, 3, 5].map(i => parseInt(v.slice(i, i + 2), 16)), X = p(a), Y = p(b);
  return '#' + X.map((v, i) => Math.round(v + (Y[i] - v) * k).toString(16).padStart(2, '0')).join('');
}
// вид набором: план строится раз (на функции), рисуется в рамку w×h (x — середина, gy — земля)
function kit(fn, w, h, build, opt, over) {
  let P = null;
  const d = (c, x, gy) => {
    if (!P) { P = plan(w, h); build(P); }
    const X0 = Math.round(x) - (w >> 1), Y0 = Math.round(gy) - h;
    paint(c, X0, Y0, P, typeof opt === 'function' ? opt() : opt);
    if (over) over(c, X0, Y0, P);
  };
  d.static = true;
  return d;
}

// перо: f(цвет|null, dx от левого края, dy — высота верха над землёй, w, h вниз)
function pen(ctx, x, gy, w) {
  const L = Math.round(x - w / 2), G = Math.round(gy);
  return (c, dx, dy, ww, hh) => { if (c) ctx.fillStyle = c; ctx.fillRect(L + dx, G - dy, ww, hh); };
}
// ступенчатая почти-вертикаль: от (dx0, dy0) вверх к (dx1, dy1); w — толщина,
// st — шаг по колонкам (2 — вдвое меньше прямоугольников для пологих раскосов)
function slope(f, c, dx0, dy0, dx1, dy1, w = 1, st = 1) {
  const n = Math.floor(Math.abs(dx1 - dx0) / st) + 1, s = Math.sign(dx1 - dx0) * st, hh = (dy1 - dy0) / n;
  f(c, dx0, Math.round(dy0 + hh), w, Math.round(hh));
  for (let i = 1; i < n; i++) {
    const a = Math.round(dy0 + hh * i), b = Math.round(dy0 + hh * (i + 1));
    f(null, dx0 + s * i, b, w, b - a);
  }
}


  f(N, 34, 24, 3, 14); f(null, 40, 24, 3, 14); f(null, 46, 24, 3, 14);
  f(null, 35, 25, 1, 1); f(null, 41, 25, 1, 1); f(null, 47, 25, 1, 1);
  f(P2, 31, 36, 4, 1); f(null, 44, 40, 6, 1); f(null, 2, 26, 4, 1);
  // башня

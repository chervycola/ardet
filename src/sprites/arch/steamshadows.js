// обод колеса радиуса r: строки пикселей, слитые в прямоугольники
function wheelRects(r) {
  const pts = new Set();
  for (let i = 0; i < 1440; i++) {
    const a = i * Math.PI / 720;
    pts.add(Math.round(r * Math.cos(a)) + ',' + Math.round(r * Math.sin(a)));
  }
  const byRow = {};
  for (const p of pts) { const [px, py] = p.split(',').map(Number); (byRow[py] = byRow[py] || []).push(px); }
  const runs = [];
  for (const k of Object.keys(byRow)) {
    const xs = byRow[k].sort((a, b) => a - b);
    let s0 = xs[0], p0 = xs[0];
    for (let i = 1; i <= xs.length; i++) {
      if (xs[i] === p0 + 1) { p0 = xs[i]; continue; }
      runs.push([s0, +k, p0 - s0 + 1, 1]); s0 = xs[i]; p0 = xs[i];
    }
  }
  runs.sort((a, b) => a[0] - b[0] || a[2] - b[2] || a[1] - b[1]);
  const out = [];
  for (const q of runs) {
    const l = out[out.length - 1];
    if (l && l[0] === q[0] && l[2] === q[2] && l[1] + l[3] === q[1]) l[3]++; else out.push(q.slice());
  }
  return out;
}
const W7 = wheelRects(7), W5 = wheelRects(5);
function wheel(f, c, cx, cy, rects) {
  let first = true;
  for (const [px, py, w, h] of rects) { f(first ? c : null, cx + px, cy - py, w, h); first = false; }
}


// перо: f(цвет|null, dx от левого края, dy — высота верха над землёй, w, h вниз)
function pen(ctx, x, gy, w) {
  const L = Math.round(x - w / 2), G = Math.round(gy);
  return (c, dx, dy, ww, hh) => { if (c) ctx.fillStyle = c; ctx.fillRect(L + dx, G - dy, ww, hh); };
}
// линия пикселями: (x, y) — в координатах пера (y — высота над землёй)
function line(f, c, x0, y0, x1, y1) {
  const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)) || 1;
  for (let i = 0; i <= n; i++) f(i ? null : c, Math.round(x0 + (x1 - x0) * i / n), Math.round(y0 + (y1 - y0) * i / n), 1, 1);
}
// окружность пикселями (обод колеса), без повторов
function ring(f, c, cx, cy, r) {
  const seen = new Set();
  let first = true;
  for (let i = 0; i < 8 * r; i++) {
    const a = i * Math.PI * 2 / (8 * r), px = cx + Math.round(r * Math.cos(a)), py = cy + Math.round(r * Math.sin(a));
    const k = px * 1000 + py;
    if (seen.has(k)) continue;
    seen.add(k); f(first ? c : null, px, py, 1, 1); first = false;
  }
}


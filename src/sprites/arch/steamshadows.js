// Башня Эйфеля в 1889-м (набором): пудлинговое железо, «красно-коричневое»; ажур — вычетом: между
// поясами и раскосами видно небо. Четыре ноги на каменных опорах; под первым ярусом — отдельная
// декоративная арка, над ней ажур и фриз (семьдесят две фамилии — штрихами); первый ярус с

// перо: f(цвет|null, dx от левого края, dy — высота верха над землёй, w, h вниз)
function pen(ctx, x, gy, w) {
  const L = Math.round(x - w / 2), G = Math.round(gy);
  return (c, dx, dy, ww, hh) => { if (c) ctx.fillStyle = c; ctx.fillRect(L + dx, G - dy, ww, hh); };
}


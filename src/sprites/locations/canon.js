// ── КРАТЕР ──
// «Монета расплавила песок... Жар сплавил стороны в одну поверхность. Ни
// орла, ни решки — гладкий диск... В центре — мох. Гуще всего там, где было
// горячее всего.» Чаша в песке: вал по кромке, склоны (левый смотрит от
// света — в тени), дно спеклось в стекло — блик полосой, трещины лучами. В
// середине — монета: гладкий диск плашмя, без рисунка; вокруг — мох, к
// монете гуще. Лежит в земле — рисуется под всем (main.js, плоское).
function craterBody() {
  const cx = 25, cy = 20, LX = -0.8, LY = -0.6;                        // свет слева-сверху
  const E = (x, y, rx, ry) => ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2;
  for (let y = cy - 14; y <= cy + 14; y++) for (let x = cx - 25; x <= cx + 25; x++) {
    const eo = E(x, y, 24, 13.5);
    if (eo > 1) continue;
    const ei = E(x, y, 18, 10), eg = E(x, y, 11, 6), d = Math.hypot((x - cx) / 24, (y - cy) / 13.5) || 1;
    const nx = (x - cx) / 24 / d, ny = (y - cy) / 13.5 / d, lit = nx * LX + ny * LY;   // нормаль наружу и свет
    let c;
    if (ei > 1.32) c = lit > 0.35 ? S1 : lit > -0.2 ? K4 : K2;          // наружный скат вала
    else if (ei > 1) c = lit > 0.62 ? L2 : lit > 0.1 ? S1 : lit > -0.4 ? S0 : K3;   // гребень вала
    else if (eg > 1) c = -lit > 0.3 ? K4 : -lit > -0.3 ? K3 : K2;       // склон чаши: светит напротив света
    else c = K1;                                                        // дно — спеклось в стекло
    r(x, y, 1, 1, c);
  }
  // стекло: блик полосой наискось, искры неба, трещины лучами
  for (let k = 0; k < 8; k++) r(cx - 8 + k, cy - 3 + q(k * 0.4), k > 2 && k < 6 ? 2 : 1, 1, k > 1 && k < 6 ? S1 : S0);
  for (const [dx, dy] of [[-6, 2], [7, -2], [4, 3]]) r(cx + dx, cy + dy, 1, 1, L1);
  r(cx + 8, cy - 1, 1, 1, BO);
  for (let a = 0; a < 7; a++) { const u = a / 7 * Math.PI * 2 + 0.3; for (let k = 7; k < 11; k++) r(cx + Math.cos(u) * k, cy + Math.sin(u) * k * 0.55, 1, 1, K0); }
  // мох — к монете гуще
  for (let k = 0; k < 170; k++) {
    const u = hh(k, 1, 3) * Math.PI * 2, d = Math.pow(hh(k, 1, 5), 1.6) * 7.5;
    r(cx + Math.cos(u) * d, cy + Math.sin(u) * d * 0.55, 1, 1, d < 2.6 ? (Math.cos(u) < 0 ? MG_L : MG) : d < 5.2 ? MG : MG_D);
  }
  // монета: гладкий диск плашмя — ни орла, ни решки, ни ребра
  r(cx - 3, cy, 7, 1, K0); r(cx - 2, cy - 1, 5, 1, L2); r(cx - 3, cy, 7, 1, L1); r(cx - 2, cy + 1, 5, 1, S0);
  r(cx - 2, cy, 1, 1, BO); r(cx - 2, cy + 2, 5, 1, K0);
}

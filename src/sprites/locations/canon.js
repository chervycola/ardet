  // оборванный провод — с повисшей траверсы через вагон к ногам; гудит — дрожит
  const [hx, hy] = HUNG, hum = t % 240 < 70 ? ((t >> 1) & 1) : 0;
  const pts = [[hx, hy], [hx - 4, 6], [hx - 8, 14], [hx - 10, 27], [hx - 16 + hum, 35], [hx - 24 + hum, 43], [16, 47]];   // через бок вагона, по днищу вниз, к ногам
  for (let i = 0; i < pts.length - 1; i++) {
    const [ax, ay] = pts[i], [bx, by] = pts[i + 1], n = Math.max(Math.abs(bx - ax), Math.abs(by - ay));
    for (let k = 0; k < n; k++) r(x + ax + (bx - ax) * k / n, y + ay + (by - ay) * k / n, 1, 1, i > 2 && k % 5 === 2 ? RUST_L : K1);
  }

function stencil(word, x0, y0) {                                         // трафарет: буквы костью, краска потекла
  [...word].forEach((ch, i) => {
    STENCIL[ch].forEach((row, j) => { for (let k = 0; k < 3; k++) if (row[k] === 'X') r(x0 + i * 4 + k, y0 + j, 1, 1, BO); });
    if (hh(i, x0, 3) < 0.45) r(x0 + i * 4 + (i % 3), y0 + 5, 1, 1 + (i & 1), L2);   // потёк
  });
}

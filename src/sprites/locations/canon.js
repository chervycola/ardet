// ── КРЕСТ НА ХОЛМЕ ──
// «Деревянный крест на вершине холма. Слишком большой для могильного. Маяк
// или предупреждение. У подножия — истлевшие цветы, свечной огарок, камень...
// На камне — четыре зарубки. Три перечёркнуты. Одна — нет. Трава у подножия
// вытоптана по кругу. Круг не размыкается.» Сцена: вкопан глубже, чем нужно
// кресту. Крест большой, тёсаный, свет слева; у основания — камни подпорой.
function crossBody() {
  const cx = 15, g = 48;
  // вершина холма: дёрн; круг вытоптан — не размыкается
  for (let x = -6; x <= 36; x++) { const top = g - 4 + q(((x - cx) / 21) ** 2 * 4); r(x, top, 1, g + 3 - top, MG_D); if (hh(x, 1, 3) < 0.6) r(x, top - 1 - (hh(x, 1, 5) < 0.3 ? 1 : 0), 1, 1 + (hh(x, 1, 5) < 0.3 ? 1 : 0), hh(x, 1, 7) < 0.4 ? MG_L : MG); }
  for (let a = 0; a < 60; a++) { const u = a / 60 * Math.PI * 2; r(cx + Math.cos(u) * 14, g - 1 + Math.sin(u) * 3.5, 2, 1, K4); }
  // крест: столб и перекладина, тёсаные; трещины, волокна
  r(cx - 2, 2, 5, g - 3, BR2); r(cx - 2, 2, 1, g - 3, RUST_L); r(cx + 2, 3, 1, g - 4, K1);
  r(cx - 13, 12, 27, 4, BR2); r(cx - 13, 12, 27, 1, RUST_L); r(cx - 13, 15, 27, 1, K1); r(cx + 13, 13, 1, 3, AS);
  for (let k = 0; k < 9; k++) r(cx - 1 + (k & 1), 18 + k * 3, 1, 2, K1);    // волокна
  for (let k = 0; k < 6; k++) r(cx - 11 + k * 4, 13 + (k & 1), 2, 1, K1);
  r(cx, 6, 1, 4, K1); r(cx - 1, 9, 1, 1, K1);                           // трещина
  r(cx - 2, 1, 5, 1, K4);                                               // торец сверху
  // подпора из камней у основания — вкопан глубже, чем нужно
  for (const [dx, w] of [[-6, 4], [-3, 3], [3, 4], [6, 3]]) { r(cx + dx - 1, g - 4, w, 3, S0); r(cx + dx - 1, g - 4, w, 1, S1); }
  // истлевшие цветы, огарок, камень с зарубками
  for (const [fx, h] of [[-9, 4], [-8, 5], [-10, 3]]) { r(cx + fx, g - 3 - h, 1, h, K4); r(cx + fx - 1, g - 4 - h, 2, 1, SEP); }
  r(cx + 6, g - 7, 2, 3, L1); r(cx + 6, g - 7, 1, 3, BO); r(cx + 7, g - 8, 1, 1, K1);   // огарок, фитиль чёрный
  r(cx + 9, g - 5, 6, 4, S0); r(cx + 9, g - 5, 6, 1, S1); r(cx + 9, g - 5, 1, 4, S1);
  for (let k = 0; k < 4; k++) { r(cx + 10 + k, g - 4, 1, 2, K1); if (k < 3) r(cx + 10 + k - 1 + (k & 1), g - 3, 2, 1, K1); }   // зарубки: три перечёркнуты
}

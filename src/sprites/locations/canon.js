  Lr(41, 16, 1, 2, KV);                                                // стоп-кран за его спиной: красная ручка, пломба цела
  Lr(30, 22, 17, 1, K1);                                               // подоконник
  Lr(36, 24, 7, 4, K2); Lr(36, 24, 7, 1, K4); Lr(36, 25, 1, 1, L2); Lr(42, 25, 1, 1, L2);   // табличка — номер стёрт
  for (const [sx, sy] of [[40, 29], [43, 30], [32, 27]]) Lr(sx, sy, 1, 2, RUST);

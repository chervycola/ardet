// ── СЛОМАННЫЙ СТОЛБ ЛЭП ──
// «Провода свисают со столбов. Один ещё гудит, хотя ток отключили одиннадцать
// лет назад. Между двумя столбами провод провис параболой... Формула провеса
// верна до сих пор.» Место — на поезде (рельсы, кабина, первый вагон), поэтому
// столбы — за поездом, к северу: левый цел, правый надломлен у земли и
// клонится, половина траверсы повисла. Между ними — провод точной параболой.
// С повисшей половины оборванный провод лёг через вагон и свернулся у ног —
// это он гудит: дрожит. Тока нет, искр нет («Палец касается меди. Не бьёт.»).
const POLE = BR2, POLE_L = RUST_L;
function pole(x0, g, H, lean) {                                         // деревянный столб на бетонном пасынке
  for (let k = 0; k < H; k++) { const xx = x0 + q(lean * k / H); r(xx, g - k, 1, 1, POLE_L); r(xx + 1, g - k, 1, 1, POLE); r(xx + 2, g - k, 1, 1, K1); }
  r(x0 - 1, g - 6, 4, 6, S0); r(x0 - 1, g - 6, 1, 6, L2); r(x0 + 2, g - 5, 1, 5, S2); r(x0 - 2, g, 6, 1, K0);
  return [x0 + q(lean) + 1, g - H];
}
let HUNG = [0, 0];                                                     // где висит оборванный провод — узнаётся при запекании
function insulator(x0, y0) { r(x0, y0 - 2, 1, 2, L1); r(x0, y0 - 2, 1, 1, BO); r(x0 - 1, y0, 3, 1, K1); }
function powerBody() {
  const g = -18;
  // левый столб цел: траверса, три изолятора; два провода оборваны и висят
  const [ax, ay] = pole(-14, g, 36, 0);
  r(ax - 9, ay + 3, 18, 2, POLE); r(ax - 9, ay + 3, 18, 1, POLE_L); r(ax - 9, ay + 5, 2, 2, K1); r(ax + 7, ay + 5, 2, 2, K1);
  for (const dx of [-8, -1, 7]) insulator(ax + dx, ay + 3);
  for (const [dx, L] of [[-8, 12], [-1, 7]]) for (let k = 0; k < L; k++) r(ax + dx + q(Math.sin(k * 0.35) * 1.4 * k / L), ay + 4 + k, 1, 1, K1);
  // правый надломлен у земли, клонится вправо; половина траверсы повисла
  const [bx, by] = pole(42, g, 34, 10);
  r(42, g - 3, 1, 2, K0); r(44, g - 4, 1, 1, L2);                      // надлом
  r(bx, by + 3, 9, 2, POLE); r(bx, by + 3, 9, 1, POLE_L); insulator(bx + 8, by + 3);
  for (let k = 0; k < 9; k++) r(bx - 1 - q(k * 0.2), by + 4 + k, 2, 1, k & 1 ? POLE : POLE_L);   // повисшая половина
  insulator(bx - 2, by + 14);
  // пролёт — точная парабола: стрела провеса семь точек
  const x1 = ax + 7, y1 = ay + 1, x2 = bx + 8, y2 = by + 1;
  for (let xx = x1; xx <= x2; xx++) { const u = (xx - x1) / (x2 - x1); r(xx, q(y1 + (y2 - y1) * u + 28 * u * (1 - u)), 1, 1, K1); }
  return [bx - 2, by + 15];
}
export function draw_powerline(x, y) {
  bake('powerline', x, y, -30, -60, 92, 46, () => { HUNG = powerBody(); });
  // оборванный провод — с повисшей траверсы через вагон к ногам; гудит — дрожит
  const [hx, hy] = HUNG, hum = t % 240 < 70 ? ((t >> 1) & 1) : 0;
  const pts = [[hx, hy], [hx - 4, 6], [hx - 8, 14], [hx - 10, 27], [hx - 16 + hum, 35], [hx - 24 + hum, 43], [16, 47]];   // через бок вагона, по днищу вниз, к ногам
  for (let i = 0; i < pts.length - 1; i++) {
    const [ax, ay] = pts[i], [bx, by] = pts[i + 1], n = Math.max(Math.abs(bx - ax), Math.abs(by - ay));
    for (let k = 0; k < n; k++) r(x + ax + (bx - ax) * k / n, y + ay + (by - ay) * k / n, 1, 1, i > 2 && k % 5 === 2 ? RUST_L : K1);
  }
  for (const [rx, ry] of [[6, 2], [4, 1]]) for (let a = 0; a < 20; a++) { const u = a / 20 * Math.PI * 2; r(x + 12 + rx * Math.cos(u), y + 47 + ry * Math.sin(u), 1, 1, a % 5 ? K1 : RUST_L); }   // свернулся на земле
}

// ── КРАТЕР ──
// «Монета расплавила песок... Жар сплавил стороны в одну поверхность. Ни
// орла, ни решки — гладкий диск... В центре — мох. Гуще всего там, где было
// горячее всего.» Чаша в песке: вал по кромке, склоны (левый смотрит от
// света — в тени), дно спеклось в стекло — блик полосой, трещины лучами. В
// середине — монета: гладкий диск плашмя, без рисунка; вокруг — мох, к
// монете гуще. Лежит в земле — рисуется под всем (main.js, плоское).
function craterBody() {
  const cx = 25, cy = 20, LX = -0.8, LY = -0.6;                        // свет слева-сверху
  const E = (x, y, rx, ry) => ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2;
  for (let y = cy - 14; y <= cy + 14; y++) for (let x = cx - 25; x <= cx + 25; x++) {
    const eo = E(x, y, 24, 13.5);
    if (eo > 1) continue;
    const ei = E(x, y, 18, 10), eg = E(x, y, 11, 6), d = Math.hypot((x - cx) / 24, (y - cy) / 13.5) || 1;
    const nx = (x - cx) / 24 / d, ny = (y - cy) / 13.5 / d, lit = nx * LX + ny * LY;   // нормаль наружу и свет
    let c;
    if (ei > 1.32) c = lit > 0.35 ? S1 : lit > -0.2 ? K4 : K2;          // наружный скат вала
    else if (ei > 1) c = lit > 0.62 ? L2 : lit > 0.1 ? S1 : lit > -0.4 ? S0 : K3;   // гребень вала
    else if (eg > 1) c = -lit > 0.3 ? K4 : -lit > -0.3 ? K3 : K2;       // склон чаши: светит напротив света
    else c = K1;                                                        // дно — спеклось в стекло
    r(x, y, 1, 1, c);
  }
  // стекло: блик полосой наискось, искры неба, трещины лучами
  for (let k = 0; k < 8; k++) r(cx - 8 + k, cy - 3 + q(k * 0.4), k > 2 && k < 6 ? 2 : 1, 1, k > 1 && k < 6 ? S1 : S0);
  for (const [dx, dy] of [[-6, 2], [7, -2], [4, 3]]) r(cx + dx, cy + dy, 1, 1, L1);
  r(cx + 8, cy - 1, 1, 1, BO);
  for (let a = 0; a < 7; a++) { const u = a / 7 * Math.PI * 2 + 0.3; for (let k = 7; k < 11; k++) r(cx + Math.cos(u) * k, cy + Math.sin(u) * k * 0.55, 1, 1, K0); }
  // мох — к монете гуще
  for (let k = 0; k < 170; k++) {
    const u = hh(k, 1, 3) * Math.PI * 2, d = Math.pow(hh(k, 1, 5), 1.6) * 7.5;
    r(cx + Math.cos(u) * d, cy + Math.sin(u) * d * 0.55, 1, 1, d < 2.6 ? (Math.cos(u) < 0 ? MG_L : MG) : d < 5.2 ? MG : MG_D);
  }
  // монета: гладкий диск плашмя — ни орла, ни решки, ни ребра
  r(cx - 3, cy, 7, 1, K0); r(cx - 2, cy - 1, 5, 1, L2); r(cx - 3, cy, 7, 1, L1); r(cx - 2, cy + 1, 5, 1, S0);
  r(cx - 2, cy, 1, 1, BO); r(cx - 2, cy + 2, 5, 1, K0);
}

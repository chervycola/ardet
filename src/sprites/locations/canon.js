// «Полукруглый каменный амфитеатр на склоне холма. Скамьи, поросшие мхом,
// спускаются к маленькой круглой сцене. На сцене четыре силуэта... один
// смеётся, один горит, один сидит, один молчит. Идёт сорок седьмой цикл.
// Каждый следующий короче предыдущего. В зале один зритель. Моргает. Иногда
// подносит к глазам светящееся — и моргает в него. У входа — афиша. Название
// стёрто... В углу — штамп пожарного надзора.» Перед сценой — гардероб: одно
// пальто, тяжёлое (сцена: theater_stage). Ярусы — дугами, врезаны в холм;
// свет слева: подступёнки левой половины смотрят от света — в тени, правой —
// к свету. Мох гуще на верхних ярусах. Два прохода лесенками.
const TH = { cx: 40, cy: 50, tiers: 6 };
const tierOf = k => ({ rx: 15 + 4.4 * k, ry: 6 + 3 * k, h: 2 + 1.6 * k });
function theaterBody() {
  const { cx, cy } = TH;
  // холм: земля с сухой травой, в нём вырезан зал
  for (let x = -3; x <= 83; x++) {
    const u = (x - cx) / 45, top = q(cy - 13 - 31 * Math.sqrt(Math.max(0, 1 - u * u)));
    r(x, top, 1, cy + 2 - top, SEP);
    r(x, top, 1, 1, K4);
    if (hh(x, 1, 3) < 0.5) r(x, top - 1, 1, 1 + q(hh(x, 1, 5) * 2), hh(x, 1, 7) < 0.3 ? MG : K4);   // сухая трава по гребню
    for (let yy = top + 3; yy < cy; yy += 3) if (hh(x, yy, 9) < 0.08) r(x, yy, 1, 1, hh(x, yy, 11) < 0.5 ? MG_D : K2);
  }
  // ярусы — от верхнего к нижнему: ступень, нос ступени, подступёнок
  for (let k = TH.tiers - 1; k >= 0; k--) {
    const { rx, ry, h } = tierOf(k), base = q(cy - h) + 4;
    const a0 = Math.ceil(cx - rx), a1 = Math.floor(cx + rx);
    for (let x = a0; x <= a1; x++) {
      const u = (x - cx) / rx, y0 = q(cy - h - ry * Math.sqrt(Math.max(0, 1 - u * u)));
      r(x, y0, 1, 1, S0); r(x, y0 + 1, 1, 1, S1);
      r(x, y0 + 2, 1, base - y0 - 2, x < cx ? K2 : S2);
      if (x === a0) r(x, y0, 1, 2, L2);                                 // торец яруса к свету
      if (hh(x, k, 37) < 0.12) r(x, y0 + 2, 1, 2, K1);                 // швы камня
      const moss = 0.06 + 0.05 * k;
      if (hh(x, k, 31) < moss) { r(x, y0, 2, 1, MG); if (hh(x, k, 33) < 0.5) r(x, y0 + 1, 1 + (hh(x, k, 39) < 0.5 ? 1 : 0), 1, MG_L); }
      if (hh(x, k, 35) < moss * 0.5) r(x, y0 + 2, 1, 1, MG_D);         // мох свисает с носа
    }
    // проходы: лесенки через ярусы
    for (const th of [0.36, 0.64]) {
      const xa = q(cx + rx * Math.cos(th * Math.PI)), u = (xa - cx) / rx, y0 = q(cy - h - ry * Math.sqrt(Math.max(0, 1 - u * u)));
      r(xa, y0, 2, 1, S1); r(xa, y0 + 2, 2, 1, S0); r(xa, y0 + 1, 2, 1, K3); r(xa, y0 + 3, 2, 1, K1);
    }
  }
  // круглая сцена: камень, край к свету, лицевая сторона к нам
  const sr = 12, sry = 3.6;
  for (let x = cx - sr; x <= cx + sr; x++) {
    const u = (x - cx) / sr, s = Math.sqrt(Math.max(0, 1 - u * u)), y0 = q(cy - sry * s), y1 = q(cy + sry * s);
    r(x, y0, 1, y1 - y0 + 1, S1);
    r(x, y0, 1, 1, x < cx ? L2 : S0);
    r(x, y1 + 1, 1, 2, x < cx + 3 ? K3 : S2); r(x, y1 + 3, 1, 1, K1);
    if (hh(x, 7, 41) < 0.1) r(x, q(cy - sry * s * 0.3), 1, 1, S2);     // плиты
    if (hh(x, 7, 43) < 0.18) r(x, y1 + 1, 1, 1, MG_D);                 // мох по шву
  }
  for (let k = 0; k < 5; k++) r(cx - 6 + k * 3, cy + (k & 1), 1, 1, S2);     // трещина поперёк сцены
  // гардероб перед сценой: вешалка, одно пальто — тяжёлое; номерок
  const gx = 60, gg = 57;
  r(gx, gg - 15, 1, 15, K1); r(gx - 2, gg - 1, 5, 1, K1); r(gx - 2, gg - 15, 5, 1, K1);
  r(gx - 3, gg - 14, 4, 9, K2); r(gx - 3, gg - 14, 1, 9, K4); r(gx - 2, gg - 14, 2, 1, L2);   // пальто, ворот
  r(gx - 2, gg - 6, 3, 1, K1); r(gx - 1, gg - 11, 1, 1, K1);
  r(gx + 1, gg - 13, 1, 2, BO);                                        // номерок
  // афиша у входа: название стёрто, строчки, в углу — штамп пожарного надзора
  const px0 = 0, pg = 56;
  r(px0 + 1, pg - 12, 1, 12, K1); r(px0 + 9, pg - 12, 1, 12, K1);
  r(px0, pg - 20, 11, 10, BR2); r(px0, pg - 20, 11, 1, L2); r(px0 + 10, pg - 19, 1, 9, AS);
  r(px0 + 1, pg - 19, 9, 8, L1); r(px0 + 1, pg - 19, 9, 1, BO);
  X.globalAlpha = 0.55; r(px0 + 2, pg - 18, 7, 2, AS); X.globalAlpha = 1;   // название стёрто
  r(px0 + 2, pg - 15, 6, 1, K4); r(px0 + 2, pg - 13, 4, 1, K4);
  X.globalAlpha = 0.8;
  for (const [dx, dy] of [[7, -14], [6, -13], [8, -13], [7, -12]]) r(px0 + dx, pg + dy, 1, 1, KV);
  X.globalAlpha = 1;
  r(px0 + 3, pg - 11, 3, 1, L1);                                       // угол отклеился
}

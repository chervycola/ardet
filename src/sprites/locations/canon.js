// ── СЛОМАННЫЙ СТОЛБ ЛЭП ──
// «Провода свисают со столбов. Один ещё гудит, хотя ток отключили одиннадцать
// лет назад. Между двумя столбами провод провис параболой... Формула провеса
// верна до сих пор.» Место — на поезде (рельсы, кабина, первый вагон), поэтому
// столбы — за поездом, к северу: левый цел, правый надломлен у земли и
// клонится, половина траверсы повисла. Между ними — провод точной параболой.
// С повисшей половины оборванный провод лёг через вагон и свернулся у ног —
// это он гудит: дрожит. Тока нет, искр нет («Палец касается меди. Не бьёт.»).
const POLE = BR2, POLE_L = RUST_L;
function pole(x0, g, H, lean) {                                         // деревянный столб на бетонном пасынке
  for (let k = 0; k < H; k++) { const xx = x0 + q(lean * k / H); r(xx, g - k, 1, 1, POLE_L); r(xx + 1, g - k, 1, 1, POLE); r(xx + 2, g - k, 1, 1, K1); }
  r(x0 - 1, g - 6, 4, 6, S0); r(x0 - 1, g - 6, 1, 6, L2); r(x0 + 2, g - 5, 1, 5, S2); r(x0 - 2, g, 6, 1, K0);
  return [x0 + q(lean) + 1, g - H];
}
let HUNG = [0, 0];                                                     // где висит оборванный провод — узнаётся при запекании
function insulator(x0, y0) { r(x0, y0 - 2, 1, 2, L1); r(x0, y0 - 2, 1, 1, BO); r(x0 - 1, y0, 3, 1, K1); }
function powerBody() {
  const g = -18;
  // левый столб цел: траверса, три изолятора; два провода оборваны и висят
  const [ax, ay] = pole(-14, g, 36, 0);
  r(ax - 9, ay + 3, 18, 2, POLE); r(ax - 9, ay + 3, 18, 1, POLE_L); r(ax - 9, ay + 5, 2, 2, K1); r(ax + 7, ay + 5, 2, 2, K1);
  for (const dx of [-8, -1, 7]) insulator(ax + dx, ay + 3);
  for (const [dx, L] of [[-8, 12], [-1, 7]]) for (let k = 0; k < L; k++) r(ax + dx + q(Math.sin(k * 0.35) * 1.4 * k / L), ay + 4 + k, 1, 1, K1);
  // правый надломлен у земли, клонится вправо; половина траверсы повисла
  const [bx, by] = pole(42, g, 34, 10);
  r(42, g - 3, 1, 2, K0); r(44, g - 4, 1, 1, L2);                      // надлом
  r(bx, by + 3, 9, 2, POLE); r(bx, by + 3, 9, 1, POLE_L); insulator(bx + 8, by + 3);
  for (let k = 0; k < 9; k++) r(bx - 1 - q(k * 0.2), by + 4 + k, 2, 1, k & 1 ? POLE : POLE_L);   // повисшая половина
  insulator(bx - 2, by + 14);
  // пролёт — точная парабола: стрела провеса семь точек
  const x1 = ax + 7, y1 = ay + 1, x2 = bx + 8, y2 = by + 1;
  for (let xx = x1; xx <= x2; xx++) { const u = (xx - x1) / (x2 - x1); r(xx, q(y1 + (y2 - y1) * u + 28 * u * (1 - u)), 1, 1, K1); }
  return [bx - 2, by + 15];
}

// поршни по бокам, траверса ходит — плита давит; на щите трафарет, «3000»
// читается; из жёлоба на рольганг выезжает свежий куб. Кубы — слоями
// спрессованной краски, всё серое; позади стена кубов (их десятки), спереди
// штабеля. Справа фура без тягача на опорах; в её борт носом вмята белая
// машина — видна сзади: номер штрихами, в заднем стекле пустое сиденье и ремень
// поперёк пустоты, у лобового — экран третьей краской (горит ровно, не мигает)
// и белый лист акта. Свет слева, кромка пеплом справа.
// куб 10×10×10 в три четверти: лицо 10×7 слоями, верх 10×3, бок 2; far — дальний ряд
function jCube(x, y, v, far) {
  const LAY = far ? [S2, K3, S2, K4, K3, S2, RUST, K3] : [S0, S2, K4, S0, RUST, S2, L2, S0, BR2, AS, S2, MG];
  for (let k = 0; k < 7; k++) r(x, y + 3 + k, 10, 1, LAY[(k * 5 + v * 3) % LAY.length]);
  r(x + 1, y, 10, 3, far ? S0 : S1); r(x + 1, y, 10, 1, far ? S1 : L2); r(x, y + 1, 1, 2, far ? S0 : S1);   // верх — к свету
  r(x + 10, y + 1, 2, 9, far ? K2 : S2); r(x + 11, y + 1, 1, 9, far ? K0 : AS);   // бок — в тени, кромка
  for (let k = 0; k < (far ? 2 : 4); k++) { const cx = x + q(hh(v, k, 131) * 8), cy = y + 4 + q(hh(v, k, 133) * 5); r(cx, cy, 2, 1, K1); r(cx + 1, cy - 1, 1, 1, far ? S2 : S1); }   // смятое: складка и блик
  if (!far && hh(v, 1, 135) < 0.45) { const wx = x + 2 + q(hh(v, 2, 137) * 4), wy = y + 4; r(wx, wy, 3, 1, K1); r(wx, wy + 3, 3, 1, K1); r(wx - 1, wy + 1, 1, 2, K1); r(wx + 3, wy + 1, 1, 2, K1); r(wx + 1, wy + 1, 1, 1, S1); }   // сплющенный обод
  if (!far && hh(v, 3, 139) < 0.5) r(x + 1 + q(hh(v, 4, 141) * 7), y + 5 + q(hh(v, 5, 143) * 3), 1, 1, AS);   // стекло
  r(x, y + 10, 12, 1, far ? K0 : K1);
}

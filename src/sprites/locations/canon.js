// ── ЗАБРОШЕННАЯ ЦЕРКОВЬ ──
// «Готический силуэт без крыши. Витражи разбиты, но рама осталась — рисует
// узоры на полу. Над входом — полустёртая латынь: LASCIATE OGNI SPERANZA. Под ней
// баллончиком: „А шо, были?" Алтарь цел. На нём — тетрадь в чёрной обложке. QR-код
// на стене.» Повторный осмотр: «Днём пустые рамы витражей кладут на пол узор…
// Узор ползёт за солнцем и к вечеру доходит до алтаря»; «QR-код… нарисован от руки,
// клетка за клеткой, по линейке». Силуэт — фасадом: контрфорсы с пинаклями (правый

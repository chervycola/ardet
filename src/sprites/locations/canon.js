  Lr(41, 35, 4, 1, K1); Lr(42, 37, 3, 1, K1); Lr(44, 33, 1, 5, K1);
  // путеочиститель — в земле; буферный брус
  for (let k = 0; k < 4; k++) Lr(-4 + k, 34 + k, 1, 6 - k, K1);
  Lr(-2, 30, 3, 3, K2); Lr(-2, 30, 1, 3, S0);

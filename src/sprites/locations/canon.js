// бок к огню подпечён, по нижнему краю кровь, капает; от лица дымок. Рисунок —
// пиксельными картами: каждая буква — краска (PAL), точка — пусто.
const BLOOD = '#6b0f1a';                                                // запёкшаяся — как на большой трубе
const SINGE = '#5a4030';                                                // подпечённое, древко к свету
const FX = 18, FY = 22;                                                 // середина огня
const MOON = [27, -33];                                                 // полумесяц — низко над огнём
const SPEAR = { base: [1, 16], top: [3, -16] };                          // копьё с черепом: древко до черепа
const SKX = -9, SKY = -38;                                              // череп на копье (левый верх карты)
const PIKE = { base: [56, 38], tip: [39, -4] };                          // пика Шута: острие — над лицом
const SKIN = '#a89878', SKIN_S = '#7a6a52';                           // кожа — тусклее кости, с тенью
const PAL = { B: BO, L: L1, l: L2, k: K4, d: K1, n: NI, s: SV, r: KV, b: BLOOD, h: K1, H: K4, c: SINGE, p: S1, P: AS, w: BR2, F: SKIN, f: SKIN_S };
function pix(rows, ox, oy) {
  for (let y = 0; y < rows.length; y++) for (let x = 0; x < rows[y].length; x++) {
    const ch = rows[y][x];
    if (ch !== '.') r(ox + x, oy + y, 1, 1, PAL[ch]);
  }
}
// череп быка анфас — половина карты, вторая зеркалом; свет слева (кость к свету
// светлее, к тени — темнее). H — рог (лирой: от затылка в стороны, вверх,
// кончики внутрь), h — кончик рога, обуглен; T — затылок; X — кость;
// E — тёмная кромка; O — провал (глазницы, носовой проём)
const SKULL_HALF = [
  '...h.........',
  '..Hh.........',
  '..H..........',
  '.HH..........',
  '.HH..........',
  '..HH.........',
  '..HHH........',
  '...HHHH......',
  '....HHHTTTTTT',
  '.....EXXXXXXX',
  '....EXXXXXXXX',
  '...EXOOXXXXXX',
  '...EXOOOXXXXX',
  '....EXXXXXXXX',
  '.....EXXXXXXX',
  '......EXXXXXO',
  '......XXXXXXO',
  '.......EXXXOO',
  '.......XXXXOO',
  '........XXXOO',
  '........XXXXX',
  '........XXX..',
  '........EE...',
];
const SKULL = SKULL_HALF.map((row, y) => {
  const full = row + row.slice(0, 12).split('').reverse().join(''), out = [];
  const is = (x, set) => x >= 0 && x < full.length && set.includes(full[x]);
  for (let x = 0; x < full.length; x++) {
    const c = full[x], left = x < 12;
    if (c === '.') out.push('.');
    else if (c === 'O') out.push('n');
    else if (c === 'E') out.push('d');
    else if (c === 'h') out.push('k');
    else if (c === 'H') out.push(left ? (is(x - 1, 'H') ? 'L' : 'B') : (is(x + 1, 'H') ? 'l' : 'k'));
    else if (c === 'T') out.push(x < 15 ? 'B' : 'l');
    else if (left) out.push(is(x - 1, 'XT') ? 'L' : 'B');
    else if (x === 12) out.push('L');
    else out.push(!is(x + 1, 'XT') ? 'k' : !is(x + 2, 'XT') ? 'l' : 'L');
  }
  // трещина по лбу и копоть — череп не новый
  if (y === 10) out[9] = 'l';
  if (y === 13) out[14] = 'k';
  if (y === 15) out[10] = 'l';
  return out.join('');
});
// наконечник копья выходит между рогами, из затылка
const BLADE = ['.P.', 'pPp', 'pPp', 'pPp', 'pPd', '.pd', '.d.'];
// лицо на пике: острие насквозь, волосы свисают набок; брови, нос, пустые
// глазницы и рот; к огню (слева) подпечено, по нижнему краю — кровь
const FACE = [
  '....P....',
  '....P....',
  '..hhPhh..',
  '.hhhhhhh.',
  'hhcFFFFhh',
  'hcFFFFFfh',
  'hcddFddfh',
  'hcnnFnnfh',
  'hcFFkFFfh',
  'h.cFkFff.',
  '..cnnnf.h',
  '..cnnnf.h',
  '...cFf..h',
  '...bfb...',
  '...b.b...',
];
function campfireBody() {
  // полумесяц над костром — низко, цвета запёкшейся крови
  const [mx, my] = MOON;
  for (let dy = -9; dy <= 9; dy++) for (let dx = -9; dx <= 9; dx++) {
    const o = dx * dx + dy * dy <= 72, cut = (dx - 4) * (dx - 4) + (dy + 1) * (dy + 1) <= 52;
    if (!o || cut) continue;
    const rim = (dx - 4) * (dx - 4) + (dy + 1) * (dy + 1) <= 66;
    r(mx + dx, my + dy, 1, 1, rim ? K1 : dx < -5 ? KV : BLOOD);
  }
  X.globalAlpha = 0.14;
  for (let a = 0; a < 40; a++) { const u = a / 40 * Math.PI * 2; if (Math.cos(u) < 0.3) r(mx + Math.cos(u) * 12, my + Math.sin(u) * 12, 1, 1, KV); }
  X.globalAlpha = 1;
  // пепел — чёрный и жирный, пятном под кольцом
  for (let y = 12; y <= 32; y++) for (let x = -2; x <= 38; x++) {
    const e = ((x - FX) / 20) ** 2 + ((y - FY) / 9) ** 2;
    if (e > 1) continue;
    r(x, y, 1, 1, e < 0.45 ? K0 : hh(x, y, 3) < 0.5 ? NI : K1);
    if (hh(x, y, 5) < 0.05) r(x, y, 1, 1, AS);                          // хлопья
  }
  // груды костей других жертв — без порядка
  const bone = (x0, y0, len, d, c = L1) => { for (let k = 0; k < len; k++) r(x0 + k * d[0], y0 + k * d[1], 1, 1, c); r(x0 - d[0], y0 - d[1], 2, 1, BO); r(x0 + len * d[0], y0 + len * d[1], 2, 1, BO); };
  for (const [bx, by, n] of [[-9, 28, 7], [39, 27, 8], [12, 35, 6]]) {
    for (let k = 0; k < n; k++) {
      const a = hh(k, bx, 3) * Math.PI, len = 2 + q(hh(k, bx, 5) * 4);
      bone(bx + q(hh(k, bx, 7) * 6), by + q(hh(k, bx, 9) * 4) - 2, len, [Math.cos(a) > 0 ? 1 : -1, Math.abs(Math.sin(a)) > 0.7 ? 1 : 0], hh(k, bx, 11) < 0.3 ? L2 : L1);
    }
  }
  r(41, 24, 4, 3, BO); r(41, 25, 1, 1, NI); r(43, 25, 1, 1, NI); r(42, 27, 2, 1, L2);   // череп поменьше — на правой груде
  r(-7, 26, 1, 1, L2); r(-8, 25, 1, 1, L2); r(-9, 23, 1, 2, L1);         // рог в левой груде
  // копьё с черепом — за кольцом слева, вбито в землю; древко чуть к огню
  const [sbx, sby] = SPEAR.base, [stx, sty] = SPEAR.top, sn = sby - sty;
  for (let k = 0; k <= sn; k++) { const xx = sbx + (stx - sbx) * k / sn, yy = sby - k; r(xx, yy, 1, 1, SINGE); r(xx + 1, yy, 1, 1, BR2); }
  r(sbx - 2, sby + 1, 6, 1, K0); r(sbx - 1, sby, 1, 1, SEP); r(sbx + 2, sby, 1, 1, SEP);   // вбито: земля бугром
  r(stx - 1, sty + 1, 4, 1, K1); r(stx - 1, sty + 2, 4, 1, SINGE);       // обмотка под черепом
  pix(BLADE, SKX + 11, SKY + 2);
  pix(SKULL, SKX, SKY);
  // кольцо закопчённых камней; кровь спеклась коркой
  for (let k = 0; k < 11; k++) {
    const a = k / 11 * Math.PI * 2 + 0.3, sx = q(FX + Math.cos(a) * 18) - 2, sy = q(FY + Math.sin(a) * 8.5) - 2, w = 4 + (k & 1), h = 3 + (k % 3 === 0 ? 1 : 0);
    r(sx - 1, sy - 1, w + 2, h + 2, K0);
    r(sx, sy, w, h, S0); r(sx, sy, w, 1, k % 3 ? K1 : S2); r(sx, sy + 1, 1, h - 1, S1); r(sx + w - 1, sy + 1, 1, h - 1, S2);   // копоть сверху
    if (hh(k, 7, 3) < 0.45) { r(sx + 1 + (k & 1), sy + 1, 2, 1, BLOOD); r(sx + 2, sy + 2, 1, 1, BLOOD); }
  }
  // скелет без головы: хребет поперёк огня; левая половина сгорела — уголь
  // с тлеющими трещинами, правая — кость; шея кончается позвонками
  for (let x = 6; x <= 25; x++) r(x, 20 - q((x - 6) * 0.12), 1, 1, x < 15 ? (x & 1 ? K1 : K4) : x & 1 ? L1 : L2);
  r(26, 17, 1, 1, L2); r(27, 17, 1, 1, BO); r(28, 16, 1, 1, L2);          // шейные позвонки — голова на копье
  for (let k = 0; k < 6; k++) {                                         // рёбра аркой
    const rx = 9 + k * 3, burnt = rx < 15;
    for (let j = 0; j < 4; j++) r(rx + (j > 2 ? 1 : 0), 19 - j - q((rx - 6) * 0.12), 1, 1, burnt ? (j > 1 ? K1 : K4) : j === 3 ? BO : L1);
    r(rx + 1, 22 - q((rx - 6) * 0.12), 1, 1, burnt ? K1 : L2);
    if (burnt) r(rx, 18 - q((rx - 6) * 0.12), 1, 1, KV);                // тлеет
  }
  r(7, 21, 1, 3, K4); r(6, 24, 2, 1, K1); r(12, 21, 1, 3, K1); r(20, 20, 1, 4, L1); r(21, 24, 2, 1, BO); r(23, 19, 1, 4, L2);   // ноги
  // пика Шута воткнута в землю, клонится к огню; на острие — лицо
  const [bx, by] = PIKE.base, [tx, ty] = PIKE.tip, fy0 = ty + 11, n = Math.max(Math.abs(tx - bx), Math.abs(fy0 - by));
  for (let k = 0; k <= n; k++) { const xx = bx + (tx - bx) * k / n, yy = by + (fy0 - by) * k / n; r(xx, yy, 1, 1, BR2); r(xx - 1, yy, 1, 1, k % 7 === 3 ? K4 : SINGE); }
  r(bx - 2, by + 1, 5, 1, K0); r(bx - 1, by, 1, 1, SEP); r(bx + 1, by, 1, 1, SEP);   // вбита в землю
  pix(FACE, tx - 4, ty);
}
export function draw_campfire(x, y) {
  bake('campfire2', x, y, -16, -46, 80, 90, campfireBody);
  // кровь с нижнего рога полумесяца: капля набухает, срывается, падает в огонь
  const dk = (t % 360) / 360, hx = x + MOON[0] + 5, hy = y + MOON[1] + 7;
  if (dk < 0.55) { const L = 1 + q(dk / 0.55 * 2); r(hx, hy, 1, L, BLOOD); r(hx, hy, 1, 1, KV); }
  else if (dk < 0.82) { const u = (dk - 0.55) / 0.27; X.globalAlpha = 1 - u * 0.6; r(hx - q(u * 2), hy + 2 + q(u * u * 30), 1, 2, BLOOD); r(hx - q(u * 2), hy + 2 + q(u * u * 30), 1, 1, KV); X.globalAlpha = 1; }
  else r(hx, hy, 1, 1, BLOOD);
  // с лица на пике капает: капля у подбородка, раз в несколько секунд
  const dl = ((t + 140) % 300) / 300, lx = x + PIKE.tip[0] - 2, ly = y + PIKE.tip[1] + 15;
  if (dl < 0.6) r(lx, ly, 1, 1 + q(dl / 0.6), BLOOD);
  else if (dl < 0.8) { const u = (dl - 0.6) / 0.2; r(lx, ly + 2 + q(u * u * 22), 1, 1, BLOOD); }
  // лицо на пике подпекается: дымок по ветру
  for (let i = 0; i < 3; i++) {
    const u = ((t * 0.4 + i * 20) % 60) / 60;
    X.globalAlpha = 0.35 * (1 - u); r(x + PIKE.tip[0] + q(Math.sin(u * 6 + i) * 1.5 + u * wind.x * 10), y + PIKE.tip[1] + 2 - q(u * 14), 1, 1, AS);
  }
  X.globalAlpha = 1;
  // тряпица на копье под черепом — киноварь, треплет ветер
  const rx = x + SPEAR.top[0] + 2, ry = y + SPEAR.top[1] + 2;
  for (let k = 0; k < 4; k++) r(rx + q(Math.sin(t * 0.07 + k * 0.8) * k * 0.4 + wind.x * k * 0.8), ry + k, k < 2 ? 2 : 1, 1, k === 0 ? BLOOD : KV);
  // огонь: языками одним силуэтом — внутри свеча, по кромке и к верху киноварь;
  // сзади тонкие киноварные языки выше; сильнее над сгоревшей половиной; по
  // ветру клонится; под ним тлеющая подложка углями
  const base = y + 23, FW = 30, FX0 = x + 3;
  for (let i = 0; i < 9; i++) r(x + 6 + i * 2 + q(hh(i, 3, 7)), base + 1 + (i & 1), 2, 1, ((t >> 3) + i) % 4 ? SV : KV);
  const TONG = [[5, 9, 2, 0], [8, 15, 3, 0], [11, 20, 4, 0], [14, 22, 4, 0], [17, 17, 3, 0], [20, 12, 3, 0], [23, 7, 2, 0],
    [9, 19, 1.5, 1], [13, 27, 1.5, 1], [16, 25, 1.5, 1], [19, 19, 1.5, 1]];
  flames(FX0, base, FW, TONG, wind.x * 4);
  // искры к луне и дым по ветру
  for (let i = 0; i < 5; i++) {
    const a = ((t * 0.5 + i * 23) % 70) / 70;
    X.globalAlpha = (1 - a) * 0.8; r(x + FX - 4 + q(Math.sin(a * 5 + i * 2) * 4 + a * wind.x * 20), y + 2 - q(a * 34), 1, 1, a < 0.4 ? SV : KV);
  }
  for (let i = 0; i < 6; i++) {
    const age = (t * 0.25 + i * 16) % 96, k = age / 96;
    X.globalAlpha = (1 - k) * 0.3; r(x + FX - 2 + q(age * wind.x * 0.5 + Math.sin(age * 0.1 + i) * 2), y + 0 - q(age * 0.3), 1 + q(k * 3), 1 + q(k * 2), AS);
  }
  X.globalAlpha = 1;
}

// ── ПИФОС ──
// «Пустая бочка Диогена. Выметено. Жилец не оставил адреса...» По ART_BIBLE
// §04 — глиняная бочка на боку, пустая, выметенная; жилец ушёл. Не деревянная
// в обручах — обожжённая глина: брюхо, плечо, горло, венчик; по брюху пояса
// волной; трещина. Зев к нам, внутри чисто — светлая полоска выметенного дна; у
// зева на пыли — следы метлы веером.
const CLAY = '#4a3420', CLAY_L = '#6b4a2c';                             // глина обожжённая: тело, к свету
function pithosBody() {
  const cx = 11, cy = 8;
  for (let y = 1; y <= 15; y++) for (let x = 0; x <= 22; x++) {          // брюхо: яйцо лёжа, к зеву сужается
    const u = (x - cx) / 11.5, rx = u > 0 ? 1 - u * u * 0.6 : 1, e = u * u + ((y - cy) / (7 * rx)) ** 2;
    if (e > 1) continue;
    r(x, y, 1, 1, y < cy - 3 ? CLAY_L : y > cy + 3 ? BR2 : CLAY);
    if (x < 4 && y < cy) r(x, y, 1, 1, CLAY_L);
  }
  for (let y = 3; y <= 12; y++) r(1, y, 1, 1, y < 7 ? L2 : CLAY);         // донце к свету
  for (const bx of [6, 12]) for (let y = 2; y <= 14; y++) if (E2(bx, y, cx, cy)) r(bx + (((y + bx) >> 1) & 1), y, 1, 1, K1);   // пояса волной
  for (let k = 0; k < 5; k++) r(15 + (k & 1), 3 + k, 1, 1, K0);           // трещина
  // горло и венчик: зев к нам, внутри выметено
  r(21, 4, 3, 9, CLAY); r(21, 4, 3, 1, CLAY_L); r(23, 4, 1, 9, AS);
  r(22, 5, 2, 7, K0); r(22, 10, 2, 1, SEP);                               // нутро; дно чистое
  r(20, 15, 5, 1, K0);
  // следы метлы веером у зева
  for (let k = 0; k < 4; k++) for (let j = 0; j < 5; j++) r(25 + j, 12 + k - q(j * (k - 1.5) * 0.3), 1, 1, j % 2 ? SEP : K4);
  X.globalAlpha = 0.45; r(1, 16, 22, 1, K0); X.globalAlpha = 1;          // лёг на землю
}
function E2(x, y, cx, cy) { const u = (x - cx) / 11.5, rx = u > 0 ? 1 - u * u * 0.6 : 1; return u * u + ((y - cy) / (7 * rx)) ** 2 <= 0.95; }
export function draw_pithos(x, y) {
  bake('pithos', x, y, -1, 0, 33, 18, pithosBody);
}


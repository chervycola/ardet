function Lr(xx, yy, w, h, c) {                                         // прямоугольник паровоза — столбцами по крену
  for (let a = xx; a < xx + w;) {
    const d = lean(a); let b = a + 1;
    while (b < xx + w && lean(b) === d) b++;
    r(a, yy + d, b - a, h, c);
    a = b;
  }
}
function disc(cx, cy, R, c) {
  for (let dy = -R; dy <= R; dy++) { const hw = q(Math.sqrt(Math.max(0, R * R - dy * dy + R * 0.6))); r(cx - hw, cy + dy, hw * 2 + 1, 1, c); }
}
function wheel(cx, cy, R) {                                            // колесо: бандаж, спицы, ступица; свет слева
  disc(cx, cy, R, K0); disc(cx, cy, R - 1, S0); disc(cx, cy, R - 2, K1);
  r(cx - R + 2, cy, 2 * R - 3, 1, S0); r(cx, cy - R + 2, 1, 2 * R - 3, S0);
  if (R > 4) for (const [dx, dy] of [[-2, -2], [2, 2], [2, -2], [-2, 2]]) r(cx + dx, cy + dy, 1, 1, S0);
  r(cx, cy, 1, 1, L2);
  r(cx - R + 1, cy - 1, 1, 2, S1); r(cx - 1, cy - R + 1, 2, 1, S1);
  r(cx + R - 1, cy + 1, 1, 2, RUST); r(cx + 1, cy + R - 1, 2, 1, RUST);
}
// вагон на боку: x0, длина, g — где днище встало на землю, v — зерно
function wagonOnSide(x0, len, g, v, chalk) {
  const top = g - 20, face = g - 11;
  // бок, ставший верхом: выцветшая мгла; дальнее ребро — крыша, ушла от нас
  r(x0 - 1, top - 1, len + 2, 21, K0);                                 // контур
  r(x0, top, len, 9, MG); r(x0, top, len, 1, MG_D);
  r(x0, top + 1, 1, 8, MG_L); r(x0 + 1, top + 8, len - 1, 1, MG_L);
  r(x0 + len - 1, top + 1, 1, 8, AS);
  for (let k = 0; x0 + 3 + k * 5 + 3 < x0 + len - 1; k++) {           // окна — ближе к крыше, стёкол нет
    const wx = x0 + 3 + k * 5;
    r(wx, top + 1, 3, 2, K0);
    if (hh(k, v, 3) < 0.4) r(wx + 2, top + 1, 1, 1, AS);               // осколок ловит небо
  }
  for (let k = 1; k < len - 1; k++) {                                  // ржа пятнами
    if (hh(k, v, 5) < 0.1) r(x0 + k, top + 3 + q(hh(k, v, 7) * 4), 1 + (hh(k, v, 9) < 0.3 ? 1 : 0), 1, RUST);
    if (hh(k, v, 15) < 0.06) r(x0 + k, top + 4, 1, 1, MG_D);           // мох
  }
  if (chalk) {                                                         // мелом, две строки: штрихи как буквы — слов не разобрать
    X.globalAlpha = 0.8;
    for (const [row, from, to, s0] of [[top + 4, 3, len - 3, 21], [top + 6, 5, len - 9, 23]]) {
      for (let cx = x0 + from, k = 0; cx < x0 + to; k++) {
        const h = hh(k, v, s0);
        if (h < 0.16) { cx += 2; continue; }
        r(cx, row + (h > 0.82 ? -1 : 0), 1, h < 0.7 ? 1 : 2, h < 0.45 ? BO : L1);
        cx += h > 0.55 ? 2 : 1;
      }
    }
    X.globalAlpha = 1;
  }
  // днище к нам: балка, тележки, оси торчком, колёса легли плашмя
  r(x0, face, len, 11, K1);
  r(x0, face, len, 1, K4); r(x0, face + 1, len, 1, K2);
  r(x0 + len - 1, face, 1, 11, K2);
  const bogies = [x0 + 3, x0 + len - 11];
  // между тележками — ящик, тормозной цилиндр, стяжка провисла
  const m = x0 + (len >> 1);
  r(m - 4, face + 3, 7, 4, K2); r(m - 4, face + 3, 7, 1, K4); r(m + 2, face + 4, 1, 3, AS);
  r(m + 5, face + 4, 3, 3, K2); r(m + 5, face + 4, 1, 1, K4);
  for (let xx = bogies[0] + 8; xx < bogies[1]; xx++) { const u = (xx - bogies[0] - 8) / (bogies[1] - bogies[0] - 8); r(xx, face + 7 + q(u * (1 - u) * 6), 1, 1, K0); }
  for (let k = 1; k < len - 1; k++) if (hh(k, v, 17) < 0.12) r(x0 + k, face + 2, 1, 2 + q(hh(k, v, 19) * 3), RUST);   // потёки ржи
  for (const bx of bogies) {
    r(bx - 1, face + 3, 10, 5, K0); r(bx, face + 3, 8, 4, K3); r(bx, face + 3, 8, 1, S0); r(bx + 3, face + 4, 2, 2, K1);
    for (const ax of [bx + 1, bx + 6]) {
      r(ax, face + 1, 1, 9, K4);                                         // ось торчком
      for (const wy of [face - 1, face + 9]) {                          // колёса легли плашмя — к нам эллипсом
        r(ax - 2, wy, 5, 1, K0); r(ax - 3, wy + 1, 7, 1, K0); r(ax - 2, wy + 2, 5, 1, K0);
        r(ax - 1, wy, 3, 1, S0); r(ax - 2, wy + 1, 5, 1, RUST_L); r(ax - 1, wy + 2, 3, 1, RUST);
        r(ax - 2, wy + 1, 1, 1, S1); r(ax, wy + 1, 1, 1, K1);
      }
    }
  }
  X.globalAlpha = 0.55; r(x0 + 1, g, len - 1, 1, K0); X.globalAlpha = 1;   // лёг всем весом
  return bogies.flatMap(b => [b + 1, b + 6]);                          // где колёса — там голо
}

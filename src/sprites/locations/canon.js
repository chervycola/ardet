// тень-человек 3×7: голова, плечи, пояс, ноги; fy — где стоят ступни
function man(x, fy, head = 0) {
  r(x + 1 + head, fy - 7, 1, 1, NI); r(x, fy - 6, 3, 3, NI); r(x + 1, fy - 3, 1, 1, NI);
  r(x, fy - 2, 1, 2, NI); r(x + 2, fy - 2, 1, 2, NI);
}
function shadowFigure(x, fy, kind, act) {
  if (kind === 'laugh') {                                              // смеётся: голова назад, рука на животе, трясётся
    const b = act && (t >> 2) & 1 ? 1 : 0;
    man(x, fy - b, act ? -1 : 0); r(x + 3, fy - 4 - b, 1, 1, NI);
  } else if (kind === 'burn') {                                        // горит: всегда, в свой черёд — выше
    man(x, fy);
    const f = act ? 2 + ((t >> 3) % 2) : (t >> 4) % 2;
    r(x + 1, fy - 8 - f, 1, f + 1, SV); if (f > 1) { r(x, fy - 8, 1, 1, KV); r(x + 2, fy - 9, 1, 1, KV); }
  } else if (kind === 'sit') {                                         // сидит на камне; в свой черёд кивает
    r(x - 1, fy - 2, 3, 2, K3); r(x - 1, fy - 2, 3, 1, S0);
    const n = act && (t >> 5) & 1 ? 1 : 0;
    r(x + 1 + n, fy - 7, 1, 1, NI); r(x, fy - 6, 3, 3, NI); r(x + 3, fy - 3, 2, 1, NI); r(x + 4, fy - 2, 1, 2, NI);
  } else {                                                             // молчит: рука у рта, не шелохнётся
    man(x, fy); r(x - 1, fy - 6, 1, 1, NI); r(x, fy - 7, 1, 1, NI);
  }
}

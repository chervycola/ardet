function hh(a, b, s) {
  let h = (a * 374761393 + b * 668265263 + s * 2246822519) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
// запекание: неподвижное рисуется один раз в свой холст — в координатах от
// угла места (x0, y0 — где холст начинается, может быть меньше нуля), дальше
// только блит; живое (свет окна, пар) — поверх, каждый кадр
// (нет холста — тесты, записывающий контекст: рисует прямо, сдвигом к месту)
const BAKED = new Map();
function bake(key, x, y, x0, y0, w, h, fn) {
  let c = BAKED.get(key);
  if (c === undefined) {
    c = typeof document !== 'undefined' && document.createElement ? document.createElement('canvas') : null;
    if (c && typeof c.getContext === 'function') {
      c.width = w; c.height = h;
      const g = c.getContext('2d'), prev = X;
      g.translate(-x0, -y0); setCtx(g);
      try { fn(); } finally { setCtx(prev); }
    } else c = null;
    BAKED.set(key, c);
  }
  if (c) { X.drawImage(c, q(x) + x0, q(y) + y0); return; }
  X.translate(q(x), q(y));
  try { fn(); } finally { X.translate(-q(x), -q(y)); }
}


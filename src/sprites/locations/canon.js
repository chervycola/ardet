// верх — небо (пусто), сквозь низ — дальняя стена; портал уступами, сквозь него
// вглубь — пол плитами, свет без крыши, у дальней стены алтарь с чёрной тетрадью,
// над ним щель окна апсиды; днём по полу ползёт узор рам (живой слой). Надписи —
// резьбой и баллончиком, слов не разобрать. Свет слева, кромка пеплом справа.
const CH_CX = 52.5, CH_G = 92;
// стрельчатая арка (равносторонняя): внутри ли пиксель; d — отступ наружу (уступы, рама)
const inArch = (x, y, cx, hw, spring, d = 0) => {
  const px = x + 0.5, py = y + 0.5;
  if (py >= spring) return Math.abs(px - cx) <= hw + d;
  const R = 2 * hw + d;
  return Math.hypot(px - (cx - hw), py - spring) <= R && Math.hypot(px - (cx + hw), py - spring) <= R;
};
const CH_BRK = [[47, -23], [49, -15], [51, -12], [53, -7], [56, -5], [60, 1], [64, 5], [68, 4], [71, 7], [74, 4], [77, 1]];   // слом щипца
const chGable = x => 14 - 1.44 * (30.5 - Math.abs(x + 0.5 - CH_CX));
function chTop(x) {                                                     // верх средней стены: щипец и слом
  let top = chGable(x);
  if (x >= 47 && x <= 77) {
    for (let i = 0; i + 1 < CH_BRK.length; i++) {
      const [x0, y0] = CH_BRK[i], [x1, y1] = CH_BRK[i + 1];
      if (x >= x0 && x <= x1) top = Math.max(top, q(y0 + (y1 - y0) * (x - x0) / (x1 - x0) + (hh(x, 9, 101) - 0.5) * 2));
    }
  }
  return Math.ceil(top);
}
// контрфорс: ширина по ярусам (уступы на 62, 34, 8), пинакль выше; s — сторона
function chButt(x, y, x0, broken) {
  const lx = x - x0;                                                    // 0..11 от внешнего края
  if (y >= 62) return lx >= 0 && lx <= 11;
  if (y >= 34) return lx >= 1 && lx <= 10;
  if (y >= 8) return lx >= 2 && lx <= 9;
  if (y >= 0) return lx >= 2 && lx <= 9 && (!broken || y >= 2 + q(hh(x, 1, 103) * 3));
  if (broken) return false;
  const hw = (y + 25) / 25 * 3.6;                                       // шпиль
  return Math.abs(lx + 0.5 - 6) <= hw;
}
// что за пиксель фасада: 'b' контрфорс, 'a' придел, 'n' средняя стена, 'f' рама окна,
// 't' переплёт, 'o' сквозь окно (пусто), 'w' дальняя стена в окне, 'r1..r3' уступы
// портала, 'h' слезник, 'p' в портале, '' — ничего
function chPart(x, y) {
  if (y > 91 || y < -26 || x < 0 || x > 105) return '';
  if (chButt(x, y, 2, false) || chButt(x, y, 92, true)) return 'b';
  if (x >= 21 && x <= 23 && y >= 3 && y < 14 && Math.abs(x - 22) <= (y - 3) / 4) return 'b';   // пинакли у плеч щипца
  if (x >= 82 && x <= 84 && y >= 3 && y < 14 && Math.abs(x - 83) <= (y - 3) / 4) return 'b';
  // портал: проём, уступы, слезник
  if (inArch(x, y, CH_CX, 6, 72)) return 'p';
  for (let k = 1; k <= 3; k++) if (inArch(x, y, CH_CX, 6, 72, 2 * k)) return 'r' + k;
  if (y < 74 && inArch(x, y, CH_CX, 6, 72, 8)) return 'h';
  // окно
  const O = y <= 44 && inArch(x, y, CH_CX, 11, 24);
  if (O) {
    const dc = Math.hypot(x + 0.5 - CH_CX, y + 0.5 - 14.5);
    if (Math.abs(dc - 4.2) < 0.75) return 't';                            // круг
    if (dc < 3.6) return (Math.abs(x + 0.5 - CH_CX) < 0.6 || Math.abs(y + 0.5 - 14.5) < 0.6) && dc < 3 ? 't' : 'o';   // крест в круге
    if (x === 52 || x === 53) return 't';                                 // средник
    const inSub = inArch(x, y, 47, 4.5, 31) || inArch(x, y, 58, 4.5, 31);
    if (y < 31 && !inSub) return 't';                                     // глухие пазухи
    if (y < 31 && (inArch(x, y, 47, 4.5, 31) && !inArch(x, y, 47, 3.5, 31) || inArch(x, y, 58, 4.5, 31) && !inArch(x, y, 58, 3.5, 31))) return 't';
    return y >= 27 ? 'w' : 'o';                                         // низ — в тени нефа, верх — небо (крыши нет)
  }
  if (y <= 45 && inArch(x, y, CH_CX, 11, 24, 2)) return 'f';
  if (y <= 45 && inArch(x, y, CH_CX, 11, 24, 3)) return 'F';
  if (x >= 14 && x <= 21 && y >= q(36 + (21 - x) * 0.7)) return 'a';
  if (x >= 84 && x <= 91 && y >= q(36 + (x - 84) * 0.7)) return 'a';
  if (x >= 22 && x <= 83 && y >= chTop(x)) return 'n';
  return '';
}
// камень кладкой: ряды по 5, швы вразбежку и не везде, камни разного тона, кое-где
// выпал камень; tone: 1 к свету, 0, −1 в тень
function chStone(x, y, tone) {
  const row = Math.floor((y + 30) / 5), sx = Math.floor((x + (row & 1) * 5) / 10), joint = (y + 30) % 5 === 0;
  const vj = (x + (row & 1) * 5) % 10 === 0 && hh(sx, row, 127) < 0.85;
  const v = hh(sx, row, 105);
  if (tone === undefined) {                                            // свет по камням, не по столбцу пикселей
    const xc = sx * 10 - (row & 1) * 5 + 5, j = (hh(sx, row, 129) - 0.5) * 12;
    tone = xc + j < 38 ? 1 : xc + j > 72 ? -1 : 0;
  }
  if (v > 0.965 && (x + (row & 1) * 5) % 10 < 5) return (y + 30) % 5 === 4 ? S1 : K1;   // выпал камень: тень в гнезде, свет по нижней кромке
  if (joint || vj) return tone < 0 ? K1 : K3;
  if (tone > 0) return v < 0.15 ? S2 : v > 0.7 ? S1 : S0;
  if (tone < 0) return v > 0.72 ? S0 : S2;
  return v < 0.2 ? S2 : v > 0.9 ? S1 : S0;
}

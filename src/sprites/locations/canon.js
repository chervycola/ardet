// ── РАЗБИТЫЙ ФОНТАН ──
// «Каменная чаша с отбитыми фигурами. Вместо воды — зеленоватая жижа. Статуя
// ангела без головы. На постаменте: «ПОМНИ». Рядом — крысиный скелет в
// миниатюрной докторской шапочке.» Сцена «Монета»: монеты на дне лицом вверх;
// очередь мелом по кругу — круг замкнут. Чаша кругом, кромка к свету; на дне
// жижа пятном, по краям сухо — монеты; на кромке — обрубки фигур (одни ступни);
// ангел на столбе: крылья, одно отбито, шея — скол. Надпись — штрихами.
function fountainBody() {
  const cx = 25, cy = 29;
  // очередь мелом по кругу — замкнута
  for (let a = 0; a < 64; a++) { if (a % 3 === 2) continue; const u = a / 64 * Math.PI * 2; r(cx + Math.cos(u) * 24, cy + 7 + Math.sin(u) * 8, 1, 1, L1); }
  // чаша: наружная стенка к нам, кромка, дно
  for (let x = cx - 20; x <= cx + 20; x++) {
    const u = (x - cx) / 20, s = Math.sqrt(Math.max(0, 1 - u * u)), top = q(cy - 7 * s), bot = q(cy + 7 * s);
    r(x, bot, 1, 6, x < cx - 8 ? S1 : x < cx + 10 ? S0 : S2); r(x, bot + 6, 1, 1, K0);   // стенка
    r(x, top, 1, bot - top + 1, S0);
    r(x, top, 1, 1, x < cx ? L2 : S1); r(x, bot, 1, 1, S1);             // кромка
  }
  for (let x = cx - 17; x <= cx + 17; x++) {                            // дно: сухо по краям, жижа в середине
    const u = (x - cx) / 17, s = Math.sqrt(Math.max(0, 1 - u * u)), top = q(cy - 5.5 * s) + 1, bot = q(cy + 5.5 * s) - 1;
    for (let y = top; y <= bot; y++) {
      const e = ((x - cx) / 12) ** 2 + ((y - cy) / 4) ** 2;
      r(x, y, 1, 1, e < 1 ? (hh(x, y, 3) < 0.15 ? MG_L : MG) : y < cy - 2 ? K3 : K4);
      if (e >= 1 && hh(x, y, 5) < 0.12) r(x, y, 1, 1, L2);              // монеты лицом вверх
    }
  }
  // обрубки фигур на кромке — одни ступни
  for (const fx of [-15, -6, 9, 16]) { const y = q(cy - 7 * Math.sqrt(1 - (fx / 20) ** 2)); r(cx + fx, y - 2, 2, 2, S1); r(cx + fx, y - 2, 1, 1, L2); r(cx + fx + 1, y - 3, 1, 1, S2); }
  // столб и постамент; на нём — «ПОМНИ» штрихами
  r(cx - 3, 13, 7, 17, S0); r(cx - 3, 13, 1, 17, S1); r(cx + 3, 14, 1, 16, S2);
  r(cx - 4, 18, 9, 4, S1); r(cx - 4, 18, 9, 1, L2); for (let k = 0; k < 5; k++) r(cx - 3 + k * 2, 19 + (k & 1), 1, 2, K1);
  // ангел без головы: ряса, крылья — правое отбито, шея — скол
  r(cx - 2, 3, 5, 10, S1); r(cx - 2, 3, 1, 10, L2); r(cx + 2, 4, 1, 9, S2);
  for (let k = 0; k < 6; k++) r(cx - 3 - k, 2 + q(k * 0.6), 1, 6 - q(k * 0.7), k & 1 ? S0 : S1);   // левое крыло
  r(cx + 3, 3, 2, 3, S0); r(cx + 4, 6, 1, 1, S2);                       // правое — обломок
  r(cx - 1, 1, 3, 2, S0); r(cx - 1, 1, 3, 1, S2);                       // скол шеи
  r(cx - 1, 7, 3, 1, S2); r(cx, 9, 1, 3, S2);                           // складки
  // жижа по столбу — потёк
  r(cx - 1, 27, 1, 2, MG); r(cx + 1, 26, 1, 3, MG_D);
  // крысиный скелет в докторской шапочке — у кромки справа
  const rx = 45, ry = 38;
  r(rx, ry, 2, 2, BO); r(rx + 2, ry + 1, 4, 1, L1); for (let k = 0; k < 3; k++) r(rx + 3 + k, ry, 1, 1, L2);   // череп, хребет, рёбра
  r(rx + 6, ry + 1, 1, 1, L2); r(rx + 7, ry + 2, 2, 1, L2); r(rx + 9, ry + 1, 1, 1, L2);   // хвост
  r(rx, ry - 2, 2, 2, BO); r(rx, ry - 2, 2, 1, L1); r(rx + 1, ry - 2, 1, 1, KV);   // шапочка, крестик
  X.globalAlpha = 0.4; r(cx - 19, cy + 13, 39, 1, K0); X.globalAlpha = 1;
}

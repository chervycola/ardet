// ── ПАЛАТКА СТАРЦА ──
// «Брезент на арматуре. Пахнет сушёными травами и мокрой шерстью. На полу —
// 9 жизней кота, записанных столбиком. 8 зачёркнуты. У входа — блюдце. Молоко
// свежее... Внутри — книги. Стопками, по возрасту. Верхние — твоего времени.
// Нижние — дочеловеческие. На корешках — инвентарные номера.» Старец сидит
// внутри — рисуется сразу после палатки (main.js: INSIDE), поэтому палатка
// даёт заднюю стенку и нутро, а он садится поверх. Каркас — ржавая арматура,
// брезент мглой в заплатах; полог откинут и привязан к левой стойке; под
// коньком сохнут травы; у задней стенки — две стопки книг по возрасту.
function tentBody() {
  // нутро: задняя стенка в тени, пол
  r(12, 9, 41, 36, K3); r(12, 9, 41, 2, K1);
  for (let x = 13; x < 52; x += 6) r(x, 12, 1, 32, K2);                 // складки брезента сзади
  r(6, 44, 53, 11, K3); for (let k = 0; k < 20; k++) r(7 + q(hh(k, 2, 3) * 50), 45 + q(hh(k, 2, 5) * 9), 1, 1, hh(k, 2, 7) < 0.5 ? K2 : K4);
  // стопки по возрасту: внизу — дочеловеческие, наверху — твоего времени; номера на корешках
  for (const [sx, base] of [[14, 44], [44, 44]]) {
    const layers = [[3, S0, S1], [2, CLAY, CLAY_L], [2, L2, BR2], [3, BR2, K4], [2, K4, S2], [2, L1, BO], [1, BO, L1]];   // камень, глина, свиток, кожа, переплёт, бумага, тонкая
    let y = base;
    layers.forEach(([h, c, e], i) => {
      const w = 6 - (i > 4 ? 1 : 0), dx = (i * 5) % 3 - 1;
      y -= h; r(sx + dx, y, w, h, c); r(sx + dx, y, w, 1, e); r(sx + dx + w - 1, y, 1, h, K1);
      r(sx + dx + 1, y + (h > 1 ? 1 : 0), 1, 1, AS);                    // инвентарный номер
    });
  }
  // девять жизней кота столбиком на полу — восемь зачёркнуты
  for (let k = 0; k < 9; k++) { r(8, 45 + k, 2, 1, L1); if (k < 8) r(10, 45 + k, 1, 1, K1); }
  // каркас: арматура, ржа
  for (const [px, y0, y1] of [[12, 8, 45], [52, 9, 45]]) { r(px, y0, 1, y1 - y0, K3); for (let y = y0; y < y1; y += 5) r(px, y + 2, 1, 1, RUST); }
  // брезент: крыша от конька к свесу, свет слева; стенки по бокам
  for (let x = 2; x <= 62; x++) {
    const u = (x - 2) / 60, ridge = 3 + q(Math.abs(u - 0.45) * 4), eave = 15 + q(u * 2) + q(Math.sin(u * Math.PI * 3) * 0.6);
    for (let y = ridge; y <= eave; y++) r(x, y, 1, 1, u < 0.3 ? MG_L : u > 0.85 ? MG_D : MG);
    r(x, ridge, 1, 1, u < 0.5 ? L2 : MG_L); r(x, eave + 1, 1, 1, K0);
  }
  for (const [x0, y0, w, h] of [[16, 6, 5, 4], [36, 9, 6, 4], [48, 7, 4, 5]]) { r(x0, y0, w, h, x0 > 40 ? SEP : K4); r(x0, y0, w, 1, MG_D); }   // заплаты
  for (const x of [22, 34, 46]) for (let y = 4; y <= 16; y += 2) r(x, y, 1, 1, MG_D);   // швы
  for (let y = 16; y <= 54; y++) { const l = 2 + q((y - 16) * 0.1), rr = 62 - q((y - 16) * 0.1); r(l, y, 3, 1, MG_D); r(l, y, 1, 1, MG); r(rr - 3, y, 4, 1, MG_D); r(rr, y, 1, 1, AS); }
  // сушёные травы — пучками на бечёвке под свесом
  for (let k = 0; k < 6; k++) { const hx = 14 + k * 7 + (k > 2 ? 2 : 0), L = 3 + (k & 1), ey = 17 + q(k * 0.35); r(hx, ey, 1, 2, L2); r(hx - 1, ey + 2, 3, L, k % 3 ? K4 : SEP); r(hx - 1, ey + 2, 1, L, MG_D); r(hx, ey + 2 + L, 1, 1, MG_D); }
  // полог откинут, привязан к левой стойке
  for (let y = 16; y <= 38; y++) { const w = 1 + q((38 - y) * 0.25); r(5, y, w, 1, MG); r(5, y, 1, 1, MG_L); }
  r(4, 30, 4, 1, L2);
  // передние стойки и растяжки к колышкам
  for (const [px, y0] of [[3, 14], [60, 16]]) { r(px, y0, 2, 55 - y0, K3); r(px, y0, 1, 55 - y0, S0); for (let y = y0; y < 55; y += 6) r(px + 1, y + 3, 1, 1, RUST); }
  for (const [ax, bx] of [[3, -6], [61, 70]]) for (let k = 0; k <= 10; k++) r(ax + (bx - ax) * k / 10, 15 + k * 3.8, 1, 1, L2);
  // блюдце у входа — молоко свежее
  r(14, 57, 6, 2, AS); r(15, 57, 4, 1, BO); r(14, 59, 6, 1, K0);
  X.globalAlpha = 0.45; r(0, 55, 66, 1, K0); X.globalAlpha = 1;
}

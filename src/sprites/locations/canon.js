// ── РАВНИНА ЛУННОГО ──
// «Выжженная равнина. Чёрный песок до горизонта, зерно к зерну одного
// размера, как просеянный. На песке — борозды. Ветра здесь нет. Борозды — от
// того, что песок когда-то пытался двигаться и перестал.» Пятно чёрного песка
// с неровной кромкой, зерно ровной сеткой, борозды застывшими волнами — гребень
// ловит свет, ложбина темней. Лежит в земле — под всем (main.js, плоское).
function plainBody() {
  const W = 60, Hh = 100, cx = 30, cy = 52;
  const edge = (x, y) => { const a = Math.atan2(y - cy, x - cx); return 1 + 0.12 * Math.sin(a * 3 + 1) + 0.07 * Math.sin(a * 7); };
  for (let y = -2; y < Hh + 2; y++) for (let x = -3; x < W + 3; x++) {
    const d = Math.hypot((x - cx) / 32, (y - cy) / 50) / edge(x, y);
    if (d > 1.04) continue;
    if (d > 0.96) { if (hh(x, y, 3) < 0.5) r(x, y, 1, 1, K1); continue; }   // кромка рассыпана
    const grain = (x % 3 === 1 && (y + (x % 6 < 3 ? 0 : 1)) % 3 === 1);       // зерно к зерну — как просеянный
    r(x, y, 1, 1, grain ? K0 : NI);
  }
  // борозды: застывшие волны поперёк, гребень к свету
  for (let k = 0; k < 9; k++) {
    const by = 14 + k * 9.5, ph = hh(k, 5, 7) * 6, amp = 1.2 + hh(k, 5, 9) * 1.5;
    for (let x = 2; x < W - 2; x++) {
      const y = q(by + Math.sin(x * 0.11 + ph) * amp + (x - cx) * (x - cx) * 0.002);
      const d = Math.hypot((x - cx) / 32, (y - cy) / 50) / edge(x, y);
      if (d > 0.9 || hh(x, k, 11) < 0.08) continue;
      r(x, y, 1, 1, K2); r(x, y + 1, 1, 1, NI);
    }
  }
}

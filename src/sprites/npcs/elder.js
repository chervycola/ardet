// СТАРЕЦ — Архивариус. По осмотру: «Старец сидит в палатке. Капюшон полностью
// закрывает лицо. Если долго смотреть — начинает казаться, что из-под капюшона
// на тебя смотрят глаза. Вокруг — книги. Некоторые открыты. На страницах —
// твой почерк. Кот сидит рядом. Молчит. У Кота своя книга, но для тебя она
// закрыта.» Сидит на камне, на коленях раскрытая книга — пишет: перо идёт по
// строке, макает в чернильницу; строка растёт. Лица нет — тьма; изредка в ней
// будто проступают глаза. Справа — стопка книг, на ней сидит кот, верхняя —
// кошачья, закрыта на застёжку. Без золота. x, y — угол места «Старец» (22×32).
// ═══════════════════════════════════════
import { t } from '../../core/time.js';
import { X } from '../../render/context.js';

const NI = '#0D0B0A', BO = '#D9CFB8', AS = '#8A8D8F', MG = '#3D4A3A';
const K0 = '#15100c', K1 = '#241c14', K2 = '#2a2620', K3 = '#34302a', K4 = '#3a3328';
const BR2 = '#3a2818', L1 = '#c8b89a', L2 = '#b0a284', S0 = '#474442', S1 = '#5e5e5d', S2 = '#33302e';
const q = Math.round;
const r = (x, y, w = 1, h = 1, c) => { X.fillStyle = c; X.fillRect(q(x), q(y), w, h); };
function hh(a, b, s) {
  let h = (a * 374761393 + b * 668265263 + s * 2246822519) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

let npcProximity = 0;
export function setProximity(v) { npcProximity = v; }

// раскрытая книга: две страницы, строки — почерком
function openBook(x, y, w, lines, seed) {
  r(x - 1, y - 1, 2 * w + 3, 5, K1);
  r(x, y, w, 3, L1); r(x + w + 1, y, w, 3, L1); r(x + w, y, 1, 3, K2); r(x, y, w, 1, BO);
  for (let k = 0; k < lines; k++) for (let j = 0; j < 2; j++) if (hh(k, j, seed) < 0.8) r(x + 1 + j * (w + 1) + q(hh(k, j, seed + 1)), y + 1 + (k & 1), w - 2 - q(hh(k, j, seed + 2) * 2), 1, K2);
}
export function drawNPC_elder(ex, ey) {
  const x0 = q(ex), y0 = q(ey), cx = x0 + 12;
  const breath = Math.sin(t * 0.005) > 0.55 ? 1 : 0;                     // вдох — плечи на точку
  // ── перо: пишет по строке, возвращается, макает ──
  const P = 360, qp = (t % P) / P, writing = qp < 0.6, prog = writing ? qp / 0.6 : 1;
  let qx, qy;
  if (writing) { qx = cx - 4 + prog * 8; qy = y0 + 21; }
  else if (qp < 0.85) { const w = (qp - 0.6) / 0.25; qx = cx + 4 + w * 6; qy = y0 + 21 - w * 4; }
  else { const w = (qp - 0.85) / 0.15; qx = cx + 10; qy = y0 + 17 + q(Math.sin(w * Math.PI) * 2); }
  // ── у ног: раскрытые книги — почерк твой; камень-сиденье ──
  openBook(x0 - 7, y0 + 32, 4, 2, 3);
  openBook(x0 + 14, y0 + 34, 3, 2, 5);
  r(cx - 10, y0 + 29, 21, 6, S0); r(cx - 10, y0 + 29, 21, 1, S1); r(cx - 10, y0 + 29, 1, 6, S1); r(cx + 10, y0 + 30, 1, 5, S2);
  r(cx - 4, y0 + 31, 1, 2, K1); r(cx + 5, y0 + 32, 1, 1, K1); r(cx - 9, y0 + 29, 2, 1, MG); r(cx + 8, y0 + 30, 1, 1, MG);
  X.globalAlpha = 0.4; r(cx - 12, y0 + 35, 25, 1, NI); X.globalAlpha = 1;
  // ── стопка книг справа: на ней сидит кот; верхняя — его, закрыта ──
  const sx = x0 + 28;
  for (const [yy, w, c, e] of [[31, 9, BR2, K4], [28, 8, S2, S0], [26, 9, K4, L2], [24, 8, K1, K3]]) { r(sx + (w < 9 ? 1 : 0), y0 + yy, w, yy === 31 ? 4 : yy === 24 ? 2 : 3 - (yy === 26 ? 1 : 0), c); r(sx + (w < 9 ? 1 : 0), y0 + yy, w, 1, e); }
  r(sx + 8, y0 + 24, 1, 2, L1); r(sx + 4, y0 + 25, 1, 1, AS);             // кошачья: обрез, застёжка
  // ── тело: сидит, колени подняты, плащ ниспадает ──
  for (let k = 0; k < 12; k++) { const y = y0 + 19 + k, w = 7 + q(k * 0.25); r(cx - w, y, 2 * w, 1, k < 3 ? K2 : K1); r(cx - w, y, 1, 1, K4); r(cx + w - 1, y, 1, 1, AS); }
  r(cx - 7, y0 + 19, 4, 2, K2); r(cx + 3, y0 + 19, 4, 2, K2);               // колени
  for (const f of [-4, 0, 4]) r(cx + f, y0 + 23, 1, 7, S2);                 // складки
  for (let k = 0; k < 12; k++) { const y = y0 + 8 + k - breath, w = 5 + q(k * 0.2); r(cx - w - 1, y, 2 * w + 1, 1, K1); r(cx - w - 1, y, 1, 1, K4); r(cx + w - 1, y, 1, 1, AS); }   // стан, сгорблен к книге
  // книга на коленях: строка растёт, пока он пишет
  r(cx - 6, y0 + 19, 13, 4, K1); r(cx - 5, y0 + 20, 5, 2, L1); r(cx + 1, y0 + 20, 5, 2, L1); r(cx, y0 + 20, 1, 2, K2);
  r(cx - 5, y0 + 20, 5, 1, K2); r(cx + 1, y0 + 20, q(5 * prog), 1, K2);    // твой почерк
  // руки: левая держит книгу, правая — перо; чернильница на камне
  r(cx - 7, y0 + 21, 2, 2, L1); r(cx - 7, y0 + 21, 1, 1, BO);
  r(cx + 9, y0 + 26, 3, 2, K0); r(cx + 10, y0 + 25, 1, 1, K1);              // чернильница
  r(qx, qy, 2, 2, L1); r(qx + 1, qy - 4, 1, 4, K1); r(qx + 2, qy - 6, 1, 3, BO); r(qx + 1, qy - 7, 1, 1, L1);   // кисть, перо
  // ── капюшон: лица нет — тьма ──
  const hx = cx - 5, hy = y0 - breath;
  r(hx + 3, hy, 5, 1, K2); r(hx + 1, hy + 1, 9, 1, K2); r(hx, hy + 2, 11, 8, K1);
  r(hx, hy + 2, 1, 7, K4); r(hx + 1, hy + 1, 2, 1, K4); r(hx + 10, hy + 3, 1, 6, AS);
  r(hx + 2, hy + 4, 7, 6, NI); r(hx + 3, hy + 3, 5, 1, NI);                // тьма — лицо закрыто целиком
  r(hx - 1, hy + 9, 13, 2, K1); r(hx - 1, hy + 9, 1, 2, K4);                // капюшон лёг на плечи
  // если долго смотреть — кажется, что из-под капюшона смотрят глаза
  const g = t % 2400;
  if (g < 150) { X.globalAlpha = 0.55 * Math.sin(g / 150 * Math.PI); r(hx + 3, hy + 6, 1, 1, AS); r(hx + 7, hy + 6, 1, 1, AS); X.globalAlpha = 1; }
}
